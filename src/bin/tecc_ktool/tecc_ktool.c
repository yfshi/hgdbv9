/*
 * tecc_ktool.c
 *   TECC Key Management Tool — offline KEK file manager
 *
 *   Generates, inspects, lists, deletes, and validates KEK files
 *   independently of any database connection.
 *
 *   Usage:
 *     tecc_ktool generate --key-name <name> --key-algo <sm4|sm2>
 *                          --key-path <dir>
 *     tecc_ktool list [--dir <path>]
 *     tecc_ktool info --key-path <path>
 *     tecc_ktool delete --key-path <path>
 *     tecc_ktool validate --key-path <path>
 *
 *   generate writes <key-name>.key (sm4) or <key-name>.priv/.pub (sm2)
 *   under the --key-path directory, and refuses to overwrite an existing
 *   file unless --force is given.
 *
 *   src/bin/tecc_ktool/tecc_ktool.c
 */

#include "postgres_fe.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <getopt.h>
#include "utils.h"
#include "tecc_ktool_common.h"

/* Forward declarations */
int get_mek(unsigned char *mek_out);
int cmd_generate(int argc, char *argv[]);
int cmd_list(int argc, char *argv[]);
int cmd_info(int argc, char *argv[]);
int cmd_delete(int argc, char *argv[]);
int cmd_validate(int argc, char *argv[]);

/* ---------- MEK: fixed master key ---------- */
#define MEK_BIN_LEN       32

/*
 * get_mek — return the compiled-in fixed MEK.
 *
 * tecc_ktool encrypts KEK files with this fixed master key, and the runtime
 * decrypt path (kms_adapter.c decrypt_kek_from_storage) uses the same fixed
 * key, so any key file generated by the tool can be decrypted at runtime.
 * No environment variable / config file is consulted — this keeps the two
 * paths consistent and avoids the "MEK rotated => old KEK files unreadable"
 * problem. The two fixed keys MUST stay identical (here and kms_adapter.c
 * FIXED_MASTER_KEY).
 */
int
get_mek(unsigned char *mek_out)
{
	static const unsigned char fixed_mek[] = {
		0x01, 0x23, 0x45, 0x67, 0x89, 0xab, 0xcd, 0xef,
		0xfe, 0xdc, 0xba, 0x98, 0x76, 0x54, 0x32, 0x10,
		0x01, 0x23, 0x45, 0x67, 0x89, 0xab, 0xcd, 0xef,
		0xfe, 0xdc, 0xba, 0x98, 0x76, 0x54, 0x32, 0x10
	};

	memcpy(mek_out, fixed_mek, MEK_BIN_LEN);
	return MEK_BIN_LEN;
}

/*
 * Print usage and exit.
 */
static void
usage(const char *progname)
{
	fprintf(stderr,
		"Usage:\n"
		"  %s generate --key-name <name> --key-algo <sm4|sm2>\n"
		"               --key-path <dir>\n"
		"  %s list [--dir <path>]\n"
		"  %s info --key-path <path>\n"
		"  %s delete --key-path <path>\n"
		"  %s validate --key-path <path>\n"
		"\n"
		"Commands:\n"
		"  generate    Generate a KEK file (sm4→<name>.key, sm2→<name>.priv+.pub)\n"
		"  list        List KEK files in a directory\n"
		"  info        Show KEK file metadata\n"
		"  delete      Delete a KEK file\n"
		"  validate    Check KEK file integrity\n"
		"\n"
		"Options:\n"
		"  --key-name    Key name; becomes the file base name\n"
		"  --key-algo    Key algorithm: 'sm4' (symmetric) or 'sm2' (SM2)\n"
		"  --key-path    Directory where the KEK file(s) are created\n"
		"  --force       Overwrite an existing KEK file (default: refuse)\n"
		"  --dir         Directory to scan (default: .)\n"
		"  --help        Show this help\n",
		progname, progname, progname, progname, progname);
}

int main(int argc, char *argv[]);

int
main(int argc, char *argv[])
{
	const char *cmd;

	/*
	 * tecc_ktool 静态链接 libpq.a，kms_adapter.o 里没有任何被本工具引用的
	 * 符号，其 TECC_CONSTRUCTOR（读 TECC_LOG_LEVEL、生产默认 WARNING）不会
	 * 被链接进二进制，日志级别会停留在 utils.c 的静态默认 DEBUG，导致每次
	 * 运行都向 stderr 刷调试日志。这里显式初始化日志系统，与 kms_adapter
	 * 的生产默认保持一致；需要临时看调试输出时用 TECC_LOG_LEVEL=DEBUG。
	 */
	{
		const char *log_level_str = getenv("TECC_LOG_LEVEL");
		LogLevel	min_level = LOG_LEVEL_WARNING;

		if (log_level_str != NULL)
		{
			if (strcmp(log_level_str, "DEBUG") == 0 ||
				strcmp(log_level_str, "DEBUG1") == 0 ||
				strcmp(log_level_str, "DEBUG2") == 0 ||
				strcmp(log_level_str, "DEBUG3") == 0 ||
				strcmp(log_level_str, "DEBUG4") == 0 ||
				strcmp(log_level_str, "DEBUG5") == 0)
				min_level = LOG_LEVEL_DEBUG;
			else if (strcmp(log_level_str, "INFO") == 0 ||
					 strcmp(log_level_str, "NOTICE") == 0)
				min_level = LOG_LEVEL_INFO;
			else if (strcmp(log_level_str, "ERROR") == 0)
				min_level = LOG_LEVEL_ERROR;
		}

		tecc_key_log_init(NULL, min_level, false);
	}

	if (argc < 2)
	{
		usage(argv[0]);
		return 1;
	}

	cmd = argv[1];

	if (strcmp(cmd, "--help") == 0 || strcmp(cmd, "-h") == 0)
	{
		usage(argv[0]);
		return 0;
	}

	if (strcmp(cmd, "generate") == 0)
		return cmd_generate(argc - 1, argv + 1);
	else if (strcmp(cmd, "list") == 0)
		return cmd_list(argc - 1, argv + 1);
	else if (strcmp(cmd, "info") == 0)
		return cmd_info(argc - 1, argv + 1);
	else if (strcmp(cmd, "delete") == 0)
		return cmd_delete(argc - 1, argv + 1);
	else if (strcmp(cmd, "validate") == 0)
		return cmd_validate(argc - 1, argv + 1);
	else
	{
		fprintf(stderr, "Unknown command: %s\n", cmd);
		fprintf(stderr, "Try '%s --help' for help.\n", argv[0]);
		return 1;
	}
}
