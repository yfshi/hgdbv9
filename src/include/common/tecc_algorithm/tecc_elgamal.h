/*-------------------------------------------------------------------------
 *
 * tecc_elgamal.h
 *	  Finite field ElGamal multiplicative homomorphic encryption
 *
 * Implements standard ElGamal over a 2048-bit prime field:
 *   - Encryption: E(m) = (c1, c2) = (g^r mod p, m * h^r mod p)
 *   - Decryption: m = c2 * (c1^x)^(-1) mod p
 *   - Homomorphic multiplication: E(a) * E(b) = E(a*b mod p)
 *
 * Decryption does NOT require DLP solving since m is recovered directly
 * via modular arithmetic.  This is the critical difference from EC-ElGamal.
 *
 * Portions Copyright (c) 2021, PostgreSQL Global Development Group
 * Portions Copyright (c) 2021, HighGo Software Co.,Ltd.
 *
 * src/include/common/tecc_algorithm/tecc_elgamal.h
 *
 *-------------------------------------------------------------------------
 */
#ifndef TECC_ELGAMAL_H
#define TECC_ELGAMAL_H

#include <openssl/bn.h>
#include <stddef.h>
#include <stdint.h>

/* ==================== Algorithm Constants ==================== */

/* 2048-bit prime field (standard mode) */
#define TECC_ELGAMAL_KEY_BITS		2048

/* Ciphertext: c1(256B) + c2(256B) = 512 bytes (standard mode) */
#define TECC_ELGAMAL_CIPHERTEXT_SIZE	512

/* Max plaintext BIGNUM byte size */
#define TECC_ELGAMAL_MAX_PLAINTEXT_SIZE	256

/* ==================== CRT Mode Constants ==================== */

/*
 * CRT mode: 2 primes of ~1024 bits each, product ~2048 bits.
 * Each 1024-bit mod_exp is ~8x faster than 2048-bit, so net ~4x speedup
 * for encrypt/decrypt at small ciphertext expansion cost.
 */
#define TECC_ELGAMAL_CRT_NUM_PRIMES		2
#define TECC_ELGAMAL_CRT_PRIME_BITS		1024

/*
 * CRT ciphertext: c1(128B) + c2(128B) per prime, 2 primes = 512 bytes.
 * Same size as standard mode.
 */
#define TECC_ELGAMAL_CRT_COMPONENT_SIZE	128
#define TECC_ELGAMAL_CRT_CIPHERTEXT_SIZE	(TECC_ELGAMAL_CRT_COMPONENT_SIZE * 2 * TECC_ELGAMAL_CRT_NUM_PRIMES)

/* ==================== Error Codes ==================== */

#define TECC_ELGAMAL_SUCCESS			0
#define TECC_ELGAMAL_ERR_NULL		-1
#define TECC_ELGAMAL_ERR_MEMORY		-2
#define TECC_ELGAMAL_ERR_CRYPTO		-3
#define TECC_ELGAMAL_ERR_SIZE		-4
#define TECC_ELGAMAL_ERR_INVALID	-5

/* ==================== Key Management ==================== */

/*
 * Standard 2048-bit ElGamal parameters (p, g).
 * Uses the IKE/2048 safe prime from RFC 5114 or similar.
 *
 * @param p Output: 2048-bit prime modulus
 * @param g Output: generator (typically 2)
 * @return 0 on success, negative on error
 */
int tecc_elgamal_generate_params(BIGNUM **p, BIGNUM **g);

/*
 * Generate an ElGamal key pair.
 *
 * The private key x is drawn uniformly from the order-q subgroup exponent
 * range [1, q-1] (q = prime order of the subgroup generated by g), so that
 * h = g^x has order exactly q and DL-security is the full 256-bit (q) strength.
 *
 * @param p Prime modulus
 * @param q Prime order of subgroup generated by g (must be prime, q | (p-1))
 * @param g Generator
 * @param priv_key Output: private key x (random, 1 <= x < q)
 * @param pub_key Output: public key h = g^x mod p
 * @return 0 on success, negative on error
 */
int tecc_elgamal_generate_keypair(const BIGNUM *p, const BIGNUM *q,
								  const BIGNUM *g,
								  BIGNUM **priv_key, BIGNUM **pub_key);

/* ==================== Core Encryption / Decryption ==================== */

/*
 * ElGamal encryption: E(m) = (c1, c2) = (g^r, m * h^r) mod p
 *
 * The ephemeral nonce r is drawn uniformly from the order-q subgroup exponent
 * range [1, q-1] (q = prime order of the subgroup generated by g), which both
 * guarantees c1 != 1 (no plaintext-in-ciphertext edge case when r is a
 * multiple of the subgroup order) and matches standard prime-order-subgroup
 * ElGamal practice.
 *
 * @param p Prime modulus
 * @param q Prime order of subgroup generated by g (must be prime, q | (p-1))
 * @param g Generator
 * @param h Public key
 * @param m Plaintext (BIGNUM)
 * @param c1 Output: c1 = g^r mod p
 * @param c2 Output: c2 = m * h^r mod p
 * @param ctx BN_CTX (or NULL for auto-create)
 * @return 0 on success, negative on error
 */
int tecc_elgamal_encrypt(const BIGNUM *p, const BIGNUM *q,
						 const BIGNUM *g, const BIGNUM *h,
						 const BIGNUM *m, BIGNUM *c1, BIGNUM *c2,
						 BN_CTX *ctx);

/*
 * ElGamal decryption: m = c2 * (c1^x)^(-1) mod p
 *
 * @param p Prime modulus
 * @param x Private key
 * @param c1 First component of ciphertext
 * @param c2 Second component of ciphertext
 * @param m Output: decrypted plaintext
 * @param ctx BN_CTX (or NULL)
 * @return 0 on success, negative on error
 */
int tecc_elgamal_decrypt(const BIGNUM *p, const BIGNUM *x,
						 const BIGNUM *c1, const BIGNUM *c2,
						 BIGNUM *m, BN_CTX *ctx);

/* ==================== Homomorphic Operations ==================== */

/*
 * ElGamal homomorphic multiplication: E(a) * E(b) = E(a*b mod p)
 * (c1, c2) = (c1_a * c1_b mod p, c2_a * c2_b mod p)
 */
int tecc_elgamal_mul(const BIGNUM *p,
					 BIGNUM *res_c1, BIGNUM *res_c2,
					 const BIGNUM *a_c1, const BIGNUM *a_c2,
					 const BIGNUM *b_c1, const BIGNUM *b_c2,
					 BN_CTX *ctx);

/*
 * ElGamal scalar multiplication (for constant plaintext k):
 * E(m) * E(k) = E(m*k mod p) where E(k) is the encryption of k.
 * This is used when a query has "enc_column * const_value".
 * The constant is encrypted server-side using the public key.
 *
 * @param q Prime order of subgroup generated by g (passed to encrypt for the
 *          ephemeral nonce range; must be prime, q | (p-1))
 */
int tecc_elgamal_mul_scalar(const BIGNUM *p, const BIGNUM *q,
							const BIGNUM *g, const BIGNUM *h,
							BIGNUM *res_c1, BIGNUM *res_c2,
							const BIGNUM *a_c1, const BIGNUM *a_c2,
							const BIGNUM *k, BN_CTX *ctx);

/*
 * ElGamal homomorphic exponentiation: E(m)^n = E(m^n mod p)
 * (c1, c2) = (c1_a^n mod p, c2_a^n mod p)
 *
 * Implemented as square-and-multiply, which is bit-identical to the naive
 * "multiply E(m) by itself n-1 times" loop: both end on the canonical
 * residue in [0, p) of the same value, so the resulting ciphertext is
 * unchanged (it stays a valid E(m^n) with randomness r*n).
 *
 * @param n Positive exponent (must be >= 1; caller validates)
 * @return 0 on success, negative on error
 */
int tecc_elgamal_pow(const BIGNUM *p,
					 BIGNUM *res_c1, BIGNUM *res_c2,
					 const BIGNUM *a_c1, const BIGNUM *a_c2,
					 const BIGNUM *n, BN_CTX *ctx);

/* ==================== Serialization ==================== */

/*
 * Serialize an ElGamal ciphertext to binary bytes.
 * Format: [c1_bytes:256] [c2_bytes:256]
 *
 * @param buf Output buffer (must be >= TECC_ELGAMAL_CIPHERTEXT_SIZE)
 * @param buf_size Size of output buffer
 * @param c1 First component
 * @param c2 Second component
 * @return Number of bytes written, or negative on error
 */
int tecc_elgamal_serialize(uint8_t *buf, int buf_size,
						   const BIGNUM *c1, const BIGNUM *c2);

/*
 * Deserialize binary bytes to ElGamal ciphertext components.
 *
 * @param c1 Output: first component
 * @param c2 Output: second component
 * @param buf Input buffer
 * @param buf_size Size of input buffer
 * @return 0 on success, negative on error
 */
int tecc_elgamal_deserialize(BIGNUM *c1, BIGNUM *c2,
							 const uint8_t *buf, int buf_size);

/* ==================== CRT Mode Type Definitions ==================== */

/*
 * CRT ElGamal parameters.
 * Uses 2 distinct 1024-bit safe primes, each with generator 2.
 * The CRT modulus N = p1 * p2 is ~2048 bits (same security footprint,
 * but operations in each subgroup benefit from smaller exponent size).
 */
typedef struct TeccElGamalCRTParams
{
	int			num_primes;		/* TECC_ELGAMAL_CRT_NUM_PRIMES = 2 */
	BIGNUM	   *primes[2];		/* 1024-bit safe primes */
	BIGNUM	   *generators[2];	/* generators (2 for both) */
	BIGNUM	   *modulus;		/* N = p1 * p2 */
} TeccElGamalCRTParams;

/*
 * CRT ElGamal ciphertext: (c1_i, c2_i) for each prime p_i.
 * Each component is 128 bytes (1024-bit), total 512 bytes.
 */
typedef struct TeccElGamalCRTCiphertext
{
	BIGNUM	   *c1[2];			/* c1_i = g_i^r mod p_i */
	BIGNUM	   *c2[2];			/* c2_i = m_i * h_i^r mod p_i */
} TeccElGamalCRTCiphertext;

/* ==================== CRT Mode Functions ==================== */

/*
 * Initialize CRT parameters with 2 standard 1024-bit safe primes.
 * Uses RFC 5114 (1024-bit MODP) and RFC 2409 (Oakley Group 2).
 * Both are well-known, audited primes with generator 2.
 *
 * @param params Output: initialized CRT parameters
 * @return 0 on success, negative on error
 */
int tecc_elgamal_crt_params_init(TeccElGamalCRTParams *params);

/*
 * Free CRT parameters.
 */
void tecc_elgamal_crt_params_free(TeccElGamalCRTParams *params);

/*
 * Allocate CRT ciphertext structure.
 */
int tecc_elgamal_crt_ciphertext_init(TeccElGamalCRTCiphertext *ct);

/*
 * Free CRT ciphertext structure.
 */
void tecc_elgamal_crt_ciphertext_free(TeccElGamalCRTCiphertext *ct);

/*
 * CRT-mode ElGamal encryption.
 * Splits plaintext m across 2 CRT primes and encrypts each.
 *
 * @param ct Output: allocated CRT ciphertext
 * @param m Plaintext BIGNUM (< CRT modulus)
 * @param params CRT parameters
 * @param h1 Public key component: g1^x mod p1
 * @param h2 Public key component: g2^x mod p2
 * @param ctx BN_CTX (or NULL)
 * @return 0 on success, negative on error
 */
int tecc_elgamal_crt_encrypt(TeccElGamalCRTCiphertext *ct,
							  const BIGNUM *m,
							  const TeccElGamalCRTParams *params,
							  const BIGNUM *h1, const BIGNUM *h2,
							  BN_CTX *ctx);

/*
 * CRT-mode ElGamal decryption.
 * Decrypts each partition and recombines via CRT.
 *
 * @param m Output: plaintext BIGNUM
 * @param ct CRT ciphertext
 * @param params CRT parameters
 * @param x Private key (same for both primes)
 * @param ctx BN_CTX (or NULL)
 * @return 0 on success, negative on error
 */
int tecc_elgamal_crt_decrypt(BIGNUM *m,
							  const TeccElGamalCRTCiphertext *ct,
							  const TeccElGamalCRTParams *params,
							  const BIGNUM *x,
							  BN_CTX *ctx);

/*
 * CRT-mode homomorphic multiplication: E(a) * E(b) = E(a*b).
 * Component-wise modular multiplication in each subgroup.
 */
int tecc_elgamal_crt_mul(TeccElGamalCRTCiphertext *res,
						  const TeccElGamalCRTCiphertext *a,
						  const TeccElGamalCRTCiphertext *b,
						  const TeccElGamalCRTParams *params,
						  BN_CTX *ctx);

/*
 * CRT-mode scalar multiplication: E(m) * k = E(m*k).
 * Encrypts k then multiplies component-wise.
 */
int tecc_elgamal_crt_mul_scalar(TeccElGamalCRTCiphertext *res,
								 const TeccElGamalCRTCiphertext *a,
								 const BIGNUM *k,
								 const TeccElGamalCRTParams *params,
								 const BIGNUM *h1, const BIGNUM *h2,
								 BN_CTX *ctx);

/*
 * Serialize CRT ciphertext to binary.
 * Format: [c1_1:128][c2_1:128][c1_2:128][c2_2:128] = 512 bytes.
 */
int tecc_elgamal_crt_serialize(uint8_t *buf, int buf_size,
								const TeccElGamalCRTCiphertext *ct);

/*
 * Deserialize binary to CRT ciphertext.
 */
int tecc_elgamal_crt_deserialize(TeccElGamalCRTCiphertext *ct,
								  const uint8_t *buf, int buf_size);

/*
 * Generate key pair components for CRT mode.
 * Same private key x used for both primes.
 * h1 = g1^x mod p1, h2 = g2^x mod p2.
 *
 * @param x Output: private key
 * @param h1 Output: public key for prime 1
 * @param h2 Output: public key for prime 2
 * @param params CRT parameters
 * @return 0 on success, negative on error
 */
int tecc_elgamal_crt_generate_keypair(BIGNUM **x, BIGNUM **h1, BIGNUM **h2,
									   const TeccElGamalCRTParams *params);

/* ==================== Utility Functions ==================== */

/*
 * Generate standard 2048-bit safe prime parameters for ElGamal.
 * Uses the well-known RFC 5114 2048-bit MODP group.
 *
 * @param p Output: allocated BIGNUM for prime
 * @param q Output: allocated BIGNUM for subgroup order ((p-1)/2)
 * @param g Output: allocated BIGNUM for generator
 * @return 0 on success, negative on error
 */
int tecc_elgamal_get_default_params(BIGNUM **p, BIGNUM **q, BIGNUM **g);

#endif /* TECC_ELGAMAL_H */
