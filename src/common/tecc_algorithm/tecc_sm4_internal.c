/* ---- 32-bit helpers ---- */

static unsigned int
rotl32(unsigned int x, int n)
{
    return (x << n) | (x >> (32 - n));
}

static unsigned int
get32_be(const unsigned char b[4])
{
    return ((unsigned int)b[0] << 24) |
           ((unsigned int)b[1] << 16) |
           ((unsigned int)b[2] <<  8) |
           ((unsigned int)b[3]);
}

static void
put32_be(unsigned char b[4], unsigned int v)
{
    b[0] = (unsigned char)(v >> 24);
    b[1] = (unsigned char)(v >> 16);
    b[2] = (unsigned char)(v >>  8);
    b[3] = (unsigned char)(v);
}

