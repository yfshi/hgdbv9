DROP OWNED BY IF EXISTS u1 CASCADE;
DROP USER IF EXISTS u1;
DROP SCHEMA IF EXISTS sch1 CASCADE;
DROP KEK IF EXISTS kek_test CASCADE;
CREATE USER u1 WITH PASSWORD 'test123';
CREATE SCHEMA sch1;
CREATE KEK kek_test WITH (KEY_STORE=localkms, KEY_PATH='/tmp/kek1.key');
GRANT USAGE ON SCHEMA sch1 TO u1;
GRANT CREATE ON SCHEMA sch1 TO u1;
GRANT USAGE ON KEK kek_test TO u1;
SET ROLE u1;
CREATE DEK sch1.dek_test WITH VALUES(KEK = kek_test);
RESET ROLE;
