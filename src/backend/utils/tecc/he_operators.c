/*
 * Generic HE scalar multiplication: a * k
 * Where a has EG_ADD slot (EC-ElGamal scalar multiplication) or
 * EG_MUL slot (ElGamal encrypt k then multiply).
 *
 * ReqID:TECC4.0 - For columns carrying BOTH slots, EG_MUL is preferred: the
 * frontend path for `enc * <constant>` encrypts the constant with the column's
 * he-mul key and evaluates he_mul_generic, so the result always carries only
 * the EG_MUL segment.  Preferring EG_MUL here keeps the plaintext-scalar path
 * (`enc * k` reaching the server via the mixed intN_enc × intN operator, or a
 * non-TECC client) producing the very same segment, so the two spellings agree
 * on the result ciphertext, on which columns accept it, and on which operators
 * it can feed (he_add_generic requires EG_ADD, he_mul_generic requires EG_MUL).
 * EC-ElGamal scalar multiplication stays the path for he-add-only columns,
 * where the scalar must be available in plaintext (k·E(a) cannot be derived
 * from E(k)).
 */
static Datum
he_mul_scalar_core(PG_FUNCTION_ARGS, Oid type_oid,
				   Datum enc_datum, int64 k_val)
{
	CipherDataType *a = (CipherDataType *) PG_DETOAST_DATUM(enc_datum);
	Oid			dek_oid;
	bool		is_ec;
	bool		has_eg_mul;
	bool		has_eg_add;
	void	   *pub_key;
	void	   *group;
	BIGNUM	   *p;
	BIGNUM	   *g;
	BIGNUM	   *q;
	CipherDataType *result;
	BN_CTX	   *bn_ctx;

	has_eg_mul = (CIPHERDATA_DATUM_EG_MUL_LEN(a) > 0);
	has_eg_add = (CIPHERDATA_DATUM_EG_ADD_LEN(a) > 0);

	if (!has_eg_mul && !has_eg_add)
		ereport(ERROR,
				(errcode(ERRCODE_TECC_ALGORITHM_INCOMPATIBLE),
				 errmsg("cannot perform scalar multiplication: "
						"column has no compatible HE ciphertext"),
				 errhint("Ensure the column has support_algo='he-add' or 'he-mul'.")));

	/* Slot choice decides which DEK is used, because a multi-DEK column
	 * binds a separate DEK to each homomorphic slot. */
	dek_oid = has_eg_mul ? CIPHERDATA_DATUM_EG_MUL_DEK_ID(a)
						 : CIPHERDATA_DATUM_EG_ADD_DEK_ID(a);

	/* ReqID:TECC4.0 - Determine key type from the chosen slot: EG_ADD -> EC,
	 * EG_MUL -> FF. Using a hardcoded prefer_ec=true here made the FF path
	 * feed an EC_POINT (65B) where a BIGNUM h (256B) was expected. */
	if (he_get_pubkey(dek_oid, !has_eg_mul,
					  &is_ec, &pub_key, &group, &p, &q, &g) != 0)
		ereport(ERROR,
				(errcode(ERRCODE_INTERNAL_ERROR),
				 errmsg("failed to retrieve HE public key")));

	bn_ctx = BN_CTX_new();
	if (bn_ctx == NULL)
		ereport(ERROR,
				(errcode(ERRCODE_OUT_OF_MEMORY),
				 errmsg("out of memory")));

	/* EC-ElGamal scalar point multiply — reached only for he-add-only columns;
	 * dual-slot columns resolved to the finite field key above. */
	if (is_ec)
	{
		TeccECCRTCiphertext ct_a;
		TeccECCRTCiphertext ct_res;
		BIGNUM	   *k_bn;

		memset(&ct_a, 0, sizeof(ct_a));
		memset(&ct_res, 0, sizeof(ct_res));

		if (tecc_ec_crt_deserialize_ex(&ct_a,
									CIPHERDATA_DATUM_EG_ADD_CT_PTR(a),
									CIPHERDATA_DATUM_EG_ADD_CT_LEN(a),
									(EC_GROUP *)group, bn_ctx) != 0)
		{
			tecc_ec_crt_ciphertext_free(&ct_a, (EC_GROUP *)group);
			BN_CTX_free(bn_ctx);
			ereport(ERROR,
					(errcode(ERRCODE_INVALID_BINARY_REPRESENTATION),
					 errmsg("invalid EC-ElGamal ciphertext")));
		}

		if (tecc_ec_crt_ciphertext_init(&ct_res, (EC_GROUP *)group,
										ct_a.num_ciphertexts) != 0)
		{
			tecc_ec_crt_ciphertext_free(&ct_a, (EC_GROUP *)group);
			BN_CTX_free(bn_ctx);
			ereport(ERROR,
					(errcode(ERRCODE_OUT_OF_MEMORY),
					 errmsg("out of memory")));
		}

		k_bn = BN_new();
		if (k_bn == NULL)
		{
			tecc_ec_crt_ciphertext_free(&ct_a, (EC_GROUP *)group);
			tecc_ec_crt_ciphertext_free(&ct_res, (EC_GROUP *)group);
			BN_CTX_free(bn_ctx);
			ereport(ERROR,
					(errcode(ERRCODE_OUT_OF_MEMORY),
					 errmsg("out of memory")));
		}
		/* ReqID:TECC4.0 - 标量按绝对值参与点乘，负号在结果密文上体现：对每个
		 * 分块的 C1/C2 同时取反等价于用随机数 -r 加密 -k*m（E(a)*(-k) =
		 * E(-k*a)），修复负标量乘（a*(-1)）丢失符号返回绝对值的问题。 */
		BN_set_word(k_bn, (BN_ULONG) (k_val >= 0 ? k_val : -k_val));

		if (tecc_ec_crt_scalar_mul((EC_GROUP *)group, &ct_res, &ct_a,
								   k_bn, bn_ctx) != 0)
		{
			BN_free(k_bn);
			tecc_ec_crt_ciphertext_free(&ct_a, (EC_GROUP *)group);
			tecc_ec_crt_ciphertext_free(&ct_res, (EC_GROUP *)group);
			BN_CTX_free(bn_ctx);
			ereport(ERROR,
					(errcode(ERRCODE_INTERNAL_ERROR),
					 errmsg("EC-ElGamal scalar multiplication failed")));
		}

		if (k_val < 0)
		{
			int		i;

			for (i = 0; i < ct_res.num_ciphertexts; i++)
			{
				EC_POINT_invert((EC_GROUP *)group, ct_res.C1[i], bn_ctx);
				EC_POINT_invert((EC_GROUP *)group, ct_res.C2[i], bn_ctx);
			}
		}

		result = build_he_add_result(&ct_res, (EC_GROUP *)group, dek_oid, bn_ctx);

		BN_free(k_bn);
		tecc_ec_crt_ciphertext_free(&ct_a, (EC_GROUP *)group);
		tecc_ec_crt_ciphertext_free(&ct_res, (EC_GROUP *)group);
		BN_CTX_free(bn_ctx);

		PG_RETURN_POINTER(result);
	}
	/* Finite field ElGamal: encrypt k then multiply.  Preferred path for
	 * dual-slot columns; the only path for he-mul-only columns. */
	else
	{
		BIGNUM *a_c1, *a_c2, *res_c1, *res_c2, *k_bn;

		a_c1 = BN_new(); a_c2 = BN_new();
		res_c1 = BN_new(); res_c2 = BN_new();
		k_bn = BN_new();

		if (a_c1 == NULL || a_c2 == NULL || res_c1 == NULL ||
			res_c2 == NULL || k_bn == NULL)
		{
			BN_free(a_c1); BN_free(a_c2);
			BN_free(res_c1); BN_free(res_c2);
			BN_free(k_bn);
			BN_CTX_free(bn_ctx);
			ereport(ERROR,
					(errcode(ERRCODE_OUT_OF_MEMORY),
					 errmsg("out of memory")));
		}

		/* ReqID:TECC4.0 - 负标量保留符号：tecc_elgamal_encrypt 内部把负明文
		 * 归一化为 p+m 加密、解密侧再按 >p/2 还原负值，E(k) 与 E(a) 相乘即得
		 * E(a*k)。原实现取绝对值导致 a*(-2) 返回 2a（丢符号）。 */
		BN_set_word(k_bn, (BN_ULONG) (k_val >= 0 ? k_val : -k_val));
		if (k_val < 0)
			BN_set_negative(k_bn, 1);

		if (tecc_elgamal_deserialize(a_c1, a_c2,
									 CIPHERDATA_DATUM_EG_MUL_CT_PTR(a),
									 CIPHERDATA_DATUM_EG_MUL_CT_LEN(a)) != 0 ||
			tecc_elgamal_mul_scalar(p, q, g, (BIGNUM *)pub_key,
									res_c1, res_c2,
									a_c1, a_c2, k_bn, bn_ctx) != 0)
		{
			BN_free(a_c1); BN_free(a_c2);
			BN_free(res_c1); BN_free(res_c2);
			BN_free(k_bn);
			BN_CTX_free(bn_ctx);
			ereport(ERROR,
					(errcode(ERRCODE_INTERNAL_ERROR),
					 errmsg("ElGamal scalar multiplication failed")));
		}

		result = build_he_mul_result(res_c1, res_c2, dek_oid);

		BN_free(a_c1); BN_free(a_c2);
		BN_free(res_c1); BN_free(res_c2);
		BN_free(k_bn);
		BN_CTX_free(bn_ctx);

		PG_RETURN_POINTER(result);
	}

	PG_RETURN_NULL(); /* unreachable */
}

