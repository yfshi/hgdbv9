/*
 * ReqID:TECC4.0 - P2-4: HE scalar addition/subtraction (enc ± constant).
 * The plain constant k is encrypted with the column's public key and added
 * to / subtracted from the EC-ElGamal ciphertext. Negative k is folded into
 * the inverse operation (a + (-k) == a - k). Requires he-add support.
 */
static Datum
he_add_scalar_core(PG_FUNCTION_ARGS, Oid type_oid, bool is_sub,
				   Datum enc_datum, int64 k_val)
{
	CipherDataType *a = (CipherDataType *) PG_DETOAST_DATUM(enc_datum);
	Oid			dek_oid;
	bool		is_ec;
	void	   *pub_key;
	void	   *group;
	BIGNUM	   *p;
	BIGNUM	   *g;
	BIGNUM	   *q;
	TeccECCRTCiphertext ct_a;
	TeccECCRTCiphertext ct_k;
	TeccECCRTCiphertext ct_res;
	TeccECCRTParams crt_params;
	BIGNUM	   *k_bn;
	CipherDataType *result;
	BN_CTX	   *bn_ctx;

	/* Validate the operand has EG_ADD data */
	if (CIPHERDATA_DATUM_EG_ADD_LEN(a) <= 0)
		ereport(ERROR,
				(errcode(ERRCODE_TECC_ALGORITHM_INCOMPATIBLE),
				 errmsg("cannot perform homomorphic scalar addition: "
						"operand lacks EG_ADD ciphertext"),
				 errhint("Ensure the column has support_algo='he-add' set.")));

	dek_oid = CIPHERDATA_DATUM_EG_ADD_DEK_ID(a);

	if (he_get_pubkey(dek_oid, true, &is_ec, &pub_key, &group, &p, &q, &g) != 0)
		ereport(ERROR,
				(errcode(ERRCODE_INTERNAL_ERROR),
				 errmsg("failed to retrieve HE public key for DEK %u", dek_oid)));

	if (!is_ec)
		ereport(ERROR,
				(errcode(ERRCODE_TECC_ALGORITHM_INCOMPATIBLE),
				 errmsg("EC-ElGamal public key required for homomorphic scalar addition")));

	bn_ctx = BN_CTX_new();
	if (bn_ctx == NULL)
		ereport(ERROR,
				(errcode(ERRCODE_OUT_OF_MEMORY),
				 errmsg("out of memory")));

	memset(&ct_a, 0, sizeof(ct_a));
	memset(&ct_k, 0, sizeof(ct_k));
	memset(&ct_res, 0, sizeof(ct_res));

	if (tecc_ec_crt_deserialize_ex(&ct_a,
								CIPHERDATA_DATUM_EG_ADD_CT_PTR(a),
								CIPHERDATA_DATUM_EG_ADD_CT_LEN(a),
								(EC_GROUP *) group, bn_ctx) != 0)
	{
		BN_CTX_free(bn_ctx);
		ereport(ERROR,
				(errcode(ERRCODE_INVALID_BINARY_REPRESENTATION),
				 errmsg("invalid EC-ElGamal ciphertext")));
	}

	/* CRT params with default primes (must match the client encryption side) */
	if (tecc_ec_crt_params_init_ex(&crt_params, TECC_EC_CRT_NUM_PRIMES) != 0)
	{
		tecc_ec_crt_ciphertext_free(&ct_a, (EC_GROUP *) group);
		BN_CTX_free(bn_ctx);
		ereport(ERROR,
				(errcode(ERRCODE_OUT_OF_MEMORY),
				 errmsg("out of memory")));
	}

	k_bn = BN_new();
	if (k_bn == NULL)
	{
		tecc_ec_crt_params_free(&crt_params);
		tecc_ec_crt_ciphertext_free(&ct_a, (EC_GROUP *) group);
		BN_CTX_free(bn_ctx);
		ereport(ERROR,
				(errcode(ERRCODE_OUT_OF_MEMORY),
				 errmsg("out of memory")));
	}

	/* Negative scalar folds into the inverse operation */
	if (k_val < 0)
	{
		is_sub = !is_sub;
		k_val = -k_val;
	}
	BN_set_word(k_bn, (BN_ULONG) k_val);

	if (tecc_ec_crt_ciphertext_init(&ct_k, (EC_GROUP *) group,
									ct_a.num_ciphertexts) != 0 ||
		tecc_ec_crt_encrypt(&ct_k, (EC_GROUP *) group, (EC_POINT *) pub_key,
							k_bn, &crt_params, bn_ctx) != 0 ||
		tecc_ec_crt_ciphertext_init(&ct_res, (EC_GROUP *) group,
									ct_a.num_ciphertexts) != 0)
	{
		BN_free(k_bn);
		tecc_ec_crt_params_free(&crt_params);
		tecc_ec_crt_ciphertext_free(&ct_a, (EC_GROUP *) group);
		tecc_ec_crt_ciphertext_free(&ct_k, (EC_GROUP *) group);
		BN_CTX_free(bn_ctx);
		ereport(ERROR,
				(errcode(ERRCODE_INTERNAL_ERROR),
				 errmsg("EC-ElGamal scalar encryption failed")));
	}

	if (is_sub)
	{
		if (tecc_ec_crt_sub((EC_GROUP *) group, &ct_res, &ct_a, &ct_k,
							bn_ctx) != 0)
		{
			BN_free(k_bn);
			tecc_ec_crt_params_free(&crt_params);
			tecc_ec_crt_ciphertext_free(&ct_a, (EC_GROUP *) group);
			tecc_ec_crt_ciphertext_free(&ct_k, (EC_GROUP *) group);
			tecc_ec_crt_ciphertext_free(&ct_res, (EC_GROUP *) group);
			BN_CTX_free(bn_ctx);
			ereport(ERROR,
					(errcode(ERRCODE_INTERNAL_ERROR),
					 errmsg("homomorphic scalar subtraction failed")));
		}
	}
	else
	{
		if (tecc_ec_crt_add((EC_GROUP *) group, &ct_res, &ct_a, &ct_k,
							bn_ctx) != 0)
		{
			BN_free(k_bn);
			tecc_ec_crt_params_free(&crt_params);
			tecc_ec_crt_ciphertext_free(&ct_a, (EC_GROUP *) group);
			tecc_ec_crt_ciphertext_free(&ct_k, (EC_GROUP *) group);
			tecc_ec_crt_ciphertext_free(&ct_res, (EC_GROUP *) group);
			BN_CTX_free(bn_ctx);
			ereport(ERROR,
					(errcode(ERRCODE_INTERNAL_ERROR),
					 errmsg("homomorphic scalar addition failed")));
		}
	}

	result = build_he_add_result(&ct_res, (EC_GROUP *) group, dek_oid, bn_ctx);

	BN_free(k_bn);
	tecc_ec_crt_params_free(&crt_params);
	tecc_ec_crt_ciphertext_free(&ct_a, (EC_GROUP *) group);
	tecc_ec_crt_ciphertext_free(&ct_k, (EC_GROUP *) group);
	tecc_ec_crt_ciphertext_free(&ct_res, (EC_GROUP *) group);
	BN_CTX_free(bn_ctx);

	PG_RETURN_POINTER(result);
}

/* ==================== ReqID:TECC4.0 - Unary Negation & Left-Constant Subtraction ==================== */

/*
 * ReqID:TECC4.0 - Negate an HE ciphertext: E(-a) computed from E(a).
 *   - EG_ADD slot (EC-ElGamal): E(-a) = E(0) - E(a).  NOTE: (C1, -C2) is
 *     NOT a valid EC-ElGamal ciphertext (decrypts to -m - 2rH), so negation
 *     must encrypt a fresh E(0) and subtract homomorphically.
 *   - EG_MUL slot (finite field ElGamal): E(-a) = (c1, p - c2), with
 *     c2 == 0 kept as 0 (avoid the out-of-range value p).
 * The result ciphertext carries only the slot used by the input, with the
 * same DEK distributed id.
 */
static CipherDataType *
he_neg_cipherdata(CipherDataType *a)
{
	Oid			dek_oid;
	bool		is_ec;
	void	   *pub_key;
	void	   *group;
	BIGNUM	   *p;
	BIGNUM	   *g;
	BIGNUM	   *q;
	CipherDataType *result;
	BN_CTX	   *bn_ctx;

	if (CIPHERDATA_DATUM_EG_ADD_LEN(a) > 0)
	{
		/* EC-ElGamal path: E(-a) = E(0) - E(a) */
		TeccECCRTCiphertext ct_a;
		TeccECCRTCiphertext ct_zero;
		TeccECCRTCiphertext ct_res;
		TeccECCRTParams crt_params;
		BIGNUM	   *k_zero;

		dek_oid = CIPHERDATA_DATUM_EG_ADD_DEK_ID(a);

		if (he_get_pubkey(dek_oid, true, &is_ec, &pub_key, &group, &p, &q, &g) != 0)
			ereport(ERROR,
					(errcode(ERRCODE_INTERNAL_ERROR),
					 errmsg("failed to retrieve HE public key")));

		if (!is_ec)
			ereport(ERROR,
					(errcode(ERRCODE_TECC_ALGORITHM_INCOMPATIBLE),
					 errmsg("EC-ElGamal public key required for homomorphic negation")));

		bn_ctx = BN_CTX_new();
		if (bn_ctx == NULL)
			ereport(ERROR,
					(errcode(ERRCODE_OUT_OF_MEMORY),
					 errmsg("out of memory")));

		memset(&ct_a, 0, sizeof(ct_a));
		memset(&ct_zero, 0, sizeof(ct_zero));
		memset(&ct_res, 0, sizeof(ct_res));

		if (tecc_ec_crt_deserialize_ex(&ct_a,
										CIPHERDATA_DATUM_EG_ADD_CT_PTR(a),
										CIPHERDATA_DATUM_EG_ADD_CT_LEN(a),
										(EC_GROUP *)group, bn_ctx) != 0)
		{
			BN_CTX_free(bn_ctx);
			ereport(ERROR,
					(errcode(ERRCODE_INVALID_BINARY_REPRESENTATION),
					 errmsg("invalid EC-ElGamal ciphertext")));
		}

		/* CRT params with default primes (must match the client side) */
		if (tecc_ec_crt_params_init_ex(&crt_params, TECC_EC_CRT_NUM_PRIMES) != 0)
		{
			tecc_ec_crt_ciphertext_free(&ct_a, (EC_GROUP *)group);
			BN_CTX_free(bn_ctx);
			ereport(ERROR,
					(errcode(ERRCODE_OUT_OF_MEMORY),
					 errmsg("out of memory")));
		}

		k_zero = BN_new();
		if (k_zero == NULL)
		{
			tecc_ec_crt_params_free(&crt_params);
			tecc_ec_crt_ciphertext_free(&ct_a, (EC_GROUP *)group);
			BN_CTX_free(bn_ctx);
			ereport(ERROR,
					(errcode(ERRCODE_OUT_OF_MEMORY),
					 errmsg("out of memory")));
		}
		BN_set_word(k_zero, 0);

		if (tecc_ec_crt_ciphertext_init(&ct_zero, (EC_GROUP *)group,
										ct_a.num_ciphertexts) != 0 ||
			tecc_ec_crt_ciphertext_init(&ct_res, (EC_GROUP *)group,
										ct_a.num_ciphertexts) != 0 ||
			tecc_ec_crt_encrypt(&ct_zero, (EC_GROUP *)group,
								(EC_POINT *)pub_key, k_zero,
								&crt_params, bn_ctx) != 0)
		{
			BN_free(k_zero);
			tecc_ec_crt_params_free(&crt_params);
			tecc_ec_crt_ciphertext_free(&ct_a, (EC_GROUP *)group);
			tecc_ec_crt_ciphertext_free(&ct_zero, (EC_GROUP *)group);
			tecc_ec_crt_ciphertext_free(&ct_res, (EC_GROUP *)group);
			BN_CTX_free(bn_ctx);
			ereport(ERROR,
					(errcode(ERRCODE_INTERNAL_ERROR),
					 errmsg("EC-ElGamal negation failed (E(0) encryption)")));
		}

		/* E(-a) = E(0) - E(a) */
		if (tecc_ec_crt_sub((EC_GROUP *)group, &ct_res, &ct_zero, &ct_a,
							bn_ctx) != 0)
		{
			BN_free(k_zero);
			tecc_ec_crt_params_free(&crt_params);
			tecc_ec_crt_ciphertext_free(&ct_a, (EC_GROUP *)group);
			tecc_ec_crt_ciphertext_free(&ct_zero, (EC_GROUP *)group);
			tecc_ec_crt_ciphertext_free(&ct_res, (EC_GROUP *)group);
			BN_CTX_free(bn_ctx);
			ereport(ERROR,
					(errcode(ERRCODE_INTERNAL_ERROR),
					 errmsg("EC-ElGamal negation failed")));
		}

		result = build_he_add_result(&ct_res, (EC_GROUP *)group, dek_oid, bn_ctx);

		BN_free(k_zero);
		tecc_ec_crt_params_free(&crt_params);
		tecc_ec_crt_ciphertext_free(&ct_a, (EC_GROUP *)group);
		tecc_ec_crt_ciphertext_free(&ct_zero, (EC_GROUP *)group);
		tecc_ec_crt_ciphertext_free(&ct_res, (EC_GROUP *)group);
		BN_CTX_free(bn_ctx);

		return result;
	}
	else if (CIPHERDATA_DATUM_EG_MUL_LEN(a) > 0)
	{
		/* Finite field ElGamal path: E(-a) = (c1, p - c2) */
		BIGNUM	   *a_c1;
		BIGNUM	   *a_c2;
		BIGNUM	   *neg_c2;

		dek_oid = CIPHERDATA_DATUM_EG_MUL_DEK_ID(a);

		if (he_get_pubkey(dek_oid, false, &is_ec, &pub_key, &group, &p, &q, &g) != 0)
			ereport(ERROR,
					(errcode(ERRCODE_INTERNAL_ERROR),
					 errmsg("failed to retrieve HE public key")));

		if (is_ec)
			ereport(ERROR,
					(errcode(ERRCODE_TECC_ALGORITHM_INCOMPATIBLE),
					 errmsg("finite field ElGamal public key required for homomorphic negation")));

		bn_ctx = BN_CTX_new();
		a_c1 = BN_new();
		a_c2 = BN_new();
		neg_c2 = BN_new();

		if (bn_ctx == NULL || a_c1 == NULL || a_c2 == NULL || neg_c2 == NULL)
		{
			BN_free(a_c1);
			BN_free(a_c2);
			BN_free(neg_c2);
			BN_CTX_free(bn_ctx);
			ereport(ERROR,
					(errcode(ERRCODE_OUT_OF_MEMORY),
					 errmsg("out of memory")));
		}

		if (tecc_elgamal_deserialize(a_c1, a_c2,
									 CIPHERDATA_DATUM_EG_MUL_CT_PTR(a),
									 CIPHERDATA_DATUM_EG_MUL_CT_LEN(a)) != 0)
		{
			BN_free(a_c1);
			BN_free(a_c2);
			BN_free(neg_c2);
			BN_CTX_free(bn_ctx);
			ereport(ERROR,
					(errcode(ERRCODE_INVALID_BINARY_REPRESENTATION),
					 errmsg("invalid ElGamal ciphertext")));
		}

		/* (p - c2) mod p: c2 == 0 yields 0, otherwise p - c2 */
		if (BN_mod_sub(neg_c2, p, a_c2, p, bn_ctx) != 1)
		{
			BN_free(a_c1);
			BN_free(a_c2);
			BN_free(neg_c2);
			BN_CTX_free(bn_ctx);
			ereport(ERROR,
					(errcode(ERRCODE_INTERNAL_ERROR),
					 errmsg("ElGamal negation failed")));
		}

		result = build_he_mul_result(a_c1, neg_c2, dek_oid);

		BN_free(a_c1);
		BN_free(a_c2);
		BN_free(neg_c2);
		BN_CTX_free(bn_ctx);

		return result;
	}

	ereport(ERROR,
			(errcode(ERRCODE_TECC_ALGORITHM_INCOMPATIBLE),
			 errmsg("cannot perform homomorphic negation: "
					"column has no compatible HE ciphertext"),
			 errhint("Ensure the column has support_algo='he-add' or 'he-mul'.")));

	pg_unreachable();
	return NULL;
}

/*
 * ReqID:TECC4.0 - Generic left-constant HE scalar subtraction: k - a
 * (constant on the left, e.g. `3 - a`).  Computes E(k) - E(a) by reusing
 * he_add_scalar_core (E(a) ± E(k)) plus he_neg_cipherdata:
 *   - k >= 0: E(k) - E(a) = -(E(a) - E(k))   → add_scalar(is_sub=true), negate
 *   - k <  0: E(k) - E(a) = -(E(a) + E(|k|)) → add_scalar(is_sub=false), negate
 * Requires he-add support (EG_ADD slot) on the encrypted operand.
 */
static Datum
he_sub_scalar_swapped_core(PG_FUNCTION_ARGS, Oid type_oid)
{
	int64		k_val;
	Datum		tmp_res;
	CipherDataType *res;

	if (type_oid == INT8_ENCOID)
		k_val = (int64) PG_GETARG_INT64(0);
	else if (type_oid == INT2_ENCOID)
		k_val = (int64) PG_GETARG_INT16(0);
	else
		k_val = (int64) PG_GETARG_INT32(0);

	if (k_val >= 0)
		tmp_res = he_add_scalar_core(fcinfo, type_oid, true,
									 PG_GETARG_DATUM(1), k_val);
	else
		tmp_res = he_add_scalar_core(fcinfo, type_oid, false,
									 PG_GETARG_DATUM(1), -k_val);

	res = he_neg_cipherdata((CipherDataType *) PG_DETOAST_DATUM(tmp_res));

	PG_RETURN_POINTER(res);
}

