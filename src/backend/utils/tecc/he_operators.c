/* ==================== Public Key Cache ==================== */

/*
 * Per-process cache for HE public keys.
 * Maps dek_dist_oid → parsed public key material.
 *
 * ReqID:TECC4.0 - 多键缓存（dynahash），按 dek_oid 缓存多个 DEK 的公钥，
 * 避免单键缓存在多 DEK 交替使用时反复释放/重建（含昂贵的 EC 点解压）。
 */

typedef enum HEKeyType
{
	HE_KEY_NONE = 0,
	HE_KEY_EC_ELGAMAL,		/* EC-ElGamal: EC_POINT *Q + EC_GROUP *group */
	HE_KEY_ELGAMAL			/* Finite field ElGamal: BIGNUM *p, *g, *h */
} HEKeyType;

typedef struct HEPubKeyCache
{
	Oid			dek_oid;		/* Cached DEK OID */
	HEKeyType	key_type;		/* Type of key */

	/* EC-ElGamal fields */
	EC_GROUP   *ec_group;
	EC_POINT   *ec_Q;			/* Public key Q = x*G */

	/* Finite field ElGamal fields */
	BIGNUM	   *ff_p;			/* Prime modulus */
	BIGNUM	   *ff_q;			/* Prime order of subgroup generated by ff_g */
	BIGNUM	   *ff_g;			/* Generator */
	BIGNUM	   *ff_h;			/* Public key h = g^x mod p */
} HEPubKeyCache;

static HTAB *he_key_cache_htab = NULL;

/* ReqID:TECC4.0 - 缓存失效回调注册标记（lazy 注册一次）。 */
static bool he_cache_callback_registered = false;

/*
 * ReqID:TECC4.0 - 释放单个缓存条目的公钥资源。
 */
static void
he_cache_entry_free(HEPubKeyCache *entry)
{
	if (entry->ec_Q != NULL)
	{
		EC_POINT_free(entry->ec_Q);
		entry->ec_Q = NULL;
	}
	if (entry->ec_group != NULL)
	{
		EC_GROUP_free(entry->ec_group);
		entry->ec_group = NULL;
	}
	if (entry->ff_p != NULL)
	{
		BN_free(entry->ff_p);
		entry->ff_p = NULL;
	}
	if (entry->ff_g != NULL)
	{
		BN_free(entry->ff_g);
		entry->ff_g = NULL;
	}
	if (entry->ff_h != NULL)
	{
		BN_free(entry->ff_h);
		entry->ff_h = NULL;
	}
	if (entry->ff_q != NULL)
	{
		BN_free(entry->ff_q);
		entry->ff_q = NULL;
	}
	entry->dek_oid = InvalidOid;
	entry->key_type = HE_KEY_NONE;
}

/*
 * Initialize the HE public key cache.
 */
void
he_pubkey_cache_init(void)
{
	HASHCTL ctl;

	if (he_key_cache_htab != NULL)
		he_pubkey_cache_invalidate();

	memset(&ctl, 0, sizeof(ctl));
	ctl.keysize = sizeof(Oid);
	ctl.entrysize = sizeof(HEPubKeyCache);
	ctl.hcxt = CacheMemoryContext;
	he_key_cache_htab = hash_create("he_pubkey_cache", 16, &ctl,
									HASH_ELEM | HASH_BLOBS | HASH_CONTEXT);
}

/*
 * ReqID:TECC4.0 - Relcache invalidation callback for the HE public key cache.
 *
 * he_key_cache_htab 缓存的是从 hg_dek/hg_dek_args 解析出的 HE 公钥。DEK 被
 * ALTER/DROP（轮换公钥）后，本进程缓存若不失效会继续用旧公钥加密常量，
 * 导致同态运算结果错误。这里监听 hg_dek 与 hg_dek_args 的关系失效事件，
 * 失效整份缓存（多键缓存无法按单 DEK 精准失效，整份失效粒度安全）。
 */
static void
he_pubkey_cache_relcallback(Datum arg, Oid relid)
{
	if (relid == InvalidOid || relid == HgDekRelationId ||
		relid == HgDekArgsRelationId)
		he_pubkey_cache_invalidate();
}

/*
 * Invalidate the cache: 释放所有缓存条目的公钥资源并销毁哈希表。
 */
void
he_pubkey_cache_invalidate(void)
{
	HASH_SEQ_STATUS status;
	HEPubKeyCache *entry;

	if (he_key_cache_htab == NULL)
		return;

	hash_seq_init(&status, he_key_cache_htab);
	while ((entry = (HEPubKeyCache *) hash_seq_search(&status)) != NULL)
		he_cache_entry_free(entry);

	hash_destroy(he_key_cache_htab);
	he_key_cache_htab = NULL;
}

/*
 * Helper: determine HE key type from hg_encrypted_columns
 *
 * Scans hg_encrypted_columns for entries referencing the given DEK,
 * and checks the encryption_type_mask for HE_ADD or HE_MUL bits.
 * This is used as a fallback when KEY_TYPE is not set in hg_dek_args.
 *
 * Returns:
 *	 true  → EC-ElGamal (HE_ADD found)
 *	 false → Finite field ElGamal (HE_MUL found, no HE_ADD)
 *
 * Now also reports whether anything was found at all: `*found` is set to true
 * when a column referencing this DEK with an HE bit was seen, false otherwise.
 * The caller uses that to tell "determined" apart from "nothing to go on" —
 * see tecc_report_undetermined_he_scheme().
 */
static void
he_detect_key_type_from_columns(Oid dek_oid, bool *is_ec, bool *found)
{
	Relation	rel;
	SysScanDesc scan;
	ScanKeyData key[1];
	HeapTuple	tup;
	bool		found_he_mul = false;

	if (found)
		*found = false;

	rel = table_open(HgEncryptedColumnsRelationId, AccessShareLock);

	/* ReqID:TECC4.0 - 走 column_key_id 索引（hg_encrypted_columns_column_key_id_index，
	 * OID 11042）。原全表扫描基于"无该索引"的过时认知，该索引自项目初始即存在，
	 * dropkek/dropdek 早已使用，此处直接复用即可，无需 catalog 变更。 */
	ScanKeyInit(&key[0],
				Anum_hg_encrypted_columns_column_key_id,
				BTEqualStrategyNumber, F_OIDEQ,
				ObjectIdGetDatum(dek_oid));

	scan = systable_beginscan(rel, HgEncryptedColumnsColumnKeyIdIndexId, true,
							  NULL, 1, key);

	while (HeapTupleIsValid(tup = systable_getnext(scan)))
	{
		Form_hg_encrypted_columns form;
		form = (Form_hg_encrypted_columns) GETSTRUCT(tup);

		/* Found a column referencing this DEK - check HE bits */
		{
			uint32 enc_mask = (uint32) form->encryption_type;

			if (enc_mask & HG_ENCRYPTION_TYPE_HE_ADD)
			{
				systable_endscan(scan);
				table_close(rel, AccessShareLock);
				*is_ec = true;	/* EC-ElGamal for additive HE */
				if (found)
					*found = true;
				return;
			}
			if (enc_mask & HG_ENCRYPTION_TYPE_HE_MUL)
			{
				found_he_mul = true;
				if (found)
					*found = true;
				/* Don't return yet - a later column might have HE_ADD */
			}
		}
	}

	systable_endscan(scan);
	table_close(rel, AccessShareLock);

	/* If we found HE_MUL but no HE_ADD, use finite field ElGamal */
	if (found_he_mul)
		*is_ec = false;
	/* else: no HE columns found, leave *is_ec unchanged */
}

/* Begin - ReqID:TECC4.0 - 同态方案定不出来时的失败关闭 */
/*
 * tecc_report_undetermined_he_scheme
 *		两条策略都没能定出某个 DEK 的同态方案时调用（hg_dek_args 里没有
 *		key_algo，也没有任何 hg_encrypted_columns 行声明它带 HE 位）。
 *
 *		此时调用方会退回默认的 EC-ElGamal（he-add）。如果密文实际是有限域
 *		ElGamal（he-mul），加/乘就会用错方案 —— 这类错误在密文上算得出来、
 *		只是算错，客户端解密后才看得出来，属最难查的一类。按
 *		hg_tecc.strict_metadata 处理（off 保持旧的静默假设）。
 */
static void
tecc_report_undetermined_he_scheme(Oid dist_id)
{
	TeccStrictMetadata level = tecc_get_strict_metadata();

	if (level == TECC_STRICT_METADATA_OFF)
		return;

	ereport(level == TECC_STRICT_METADATA_ERROR ? ERROR : WARNING,
			(errcode(ERRCODE_OBJECT_NOT_IN_PREREQUISITE_STATE),
			 errmsg("cannot determine the homomorphic scheme of DEK with distributed id %u",
					dist_id),
			 errdetail("Neither hg_dek_args.key_algo nor any hg_encrypted_columns row "
					   "identifies this key as he-add or he-mul, so EC-ElGamal "
					   "(additive) is assumed."),
			 errhint("Recreate the DEK with an explicit he-add/he-mul algorithm. "
					 "Set hg_tecc.strict_metadata to 'off' to keep assuming "
					 "EC-ElGamal.")));
}
/* End - ReqID:TECC4.0 - 同态方案定不出来时的失败关闭 */

/*
 * Resolve a DEK's real hg_dek.oid from its distributed ID.
 *
 * CipherDataType carries dek_dist_oid = column_key_distributed_id (a hash),
 * not the hg_dek.oid. hg_dek_args rows are keyed by hg_dek.oid, so we must
 * translate distributed ID -> hg_dek.oid before reading hg_dek_args.
 *
 * Returns true and sets *real_oid on success; false if not found.
 */
static bool
he_resolve_dek_oid(Oid dist_id, Oid *real_oid)
{
	Relation	rel;
	SysScanDesc scan;
	ScanKeyData key[1];
	HeapTuple	tup;

	*real_oid = InvalidOid;
	if (!OidIsValid(dist_id))
		return false;

	rel = table_open(HgDekRelationId, AccessShareLock);
	ScanKeyInit(&key[0], Anum_hg_dek_column_key_distributed_id,
				BTEqualStrategyNumber, F_OIDEQ, ObjectIdGetDatum(dist_id));
	scan = systable_beginscan(rel, HgDekDistributedIdIndexId, true, NULL, 1, key);

	tup = systable_getnext(scan);
	if (HeapTupleIsValid(tup))
	{
		Form_hg_dek form = (Form_hg_dek) GETSTRUCT(tup);
		*real_oid = form->oid;

	}
	systable_endscan(scan);
	table_close(rel, AccessShareLock);

	return OidIsValid(*real_oid);
}

/*
 * Load the real HE public key (hex in hg_dek_args) and decode it.
 *
 * @param dist_id DEK distributed ID from CipherDataType
 * @param is_ec   true = EC-ElGamal (he_ec_pubkey), false = FF (he_eg_pubkey)
 * @param ec_group EC group (for EC decode; may be NULL if !is_ec)
 * @param ec_out   Output EC point (if is_ec)
 * @param ff_out   Output BIGNUM (if !is_ec)
 * @return 0 on success (real key loaded), -1 if not found/failed
 */
static int
he_load_real_pubkey(Oid dist_id, bool is_ec, EC_GROUP *ec_group,
					EC_POINT **ec_out, BIGNUM **ff_out)
{
	Oid			real_oid = InvalidOid;
	char	   *pub_hex;
	unsigned char *pub_bin;
	int			pub_bin_len;
	int			i;

	if (ec_out)
		*ec_out = NULL;
	if (ff_out)
		*ff_out = NULL;

	/* Translate distributed ID to real hg_dek.oid */
	if (!he_resolve_dek_oid(dist_id, &real_oid))
	{

		return -1;
	}


	/* Read the stored public key hex (bytea = ASCII hex chars) */
	pub_hex = get_dek_arg_value(real_oid, is_ec ? "he_ec_pubkey" : "he_eg_pubkey");
	if (pub_hex == NULL || pub_hex[0] == '\0')
	{

		if (pub_hex)
			pfree(pub_hex);
		return -1;
	}


	pub_bin_len = strlen(pub_hex) / 2;
	pub_bin = (unsigned char *) palloc(pub_bin_len);
	for (i = 0; i < pub_bin_len; i++)
	{
		char		c1 = pub_hex[i * 2];
		char		c2 = pub_hex[i * 2 + 1];
		unsigned char n1, n2;

		n1 = (c1 >= '0' && c1 <= '9') ? (unsigned char) (c1 - '0') :
			(c1 >= 'a' && c1 <= 'f') ? (unsigned char) (c1 - 'a' + 10) :
			(c1 >= 'A' && c1 <= 'F') ? (unsigned char) (c1 - 'A' + 10) : 0;
		n2 = (c2 >= '0' && c2 <= '9') ? (unsigned char) (c2 - '0') :
			(c2 >= 'a' && c2 <= 'f') ? (unsigned char) (c2 - 'a' + 10) :
			(c2 >= 'A' && c2 <= 'F') ? (unsigned char) (c2 - 'A' + 10) : 0;
		pub_bin[i] = (n1 << 4) | n2;
	}
	pfree(pub_hex);

	if (is_ec)
	{
		EC_POINT *pt = EC_POINT_new(ec_group);

		if (pt != NULL &&
			EC_POINT_oct2point(ec_group, pt, pub_bin, pub_bin_len, NULL) == 1)
		{
			*ec_out = pt;
			pfree(pub_bin);
			return 0;
		}
		if (pt)
			EC_POINT_free(pt);
	}
	else
	{
		BIGNUM *bn = BN_bin2bn(pub_bin, pub_bin_len, NULL);

		if (bn != NULL)
		{
			*ff_out = bn;
			pfree(pub_bin);
			return 0;
		}
	}
	pfree(pub_bin);
	return -1;
}

/*
 * Fetch HE public key type from hg_dek_args by DEK OID.
 *
 * Looks up the DEK's key_algo entry in hg_dek_args to determine
 * whether this DEK uses EC-ElGamal (additive HE, he-add) or finite
 * field ElGamal (multiplicative HE, he-mul).  Falls back to detecting
 * the type from hg_encrypted_columns if key_algo is not set.
 *
 * For now, this function determines the key type from metadata.
 * The actual public key material (Q or h) will be populated in a
 * later phase when key generation is added to the DEK creation flow.
 */
int
he_fetch_pubkey_from_dek(Oid dek_oid,
						 bool *is_ec_elgamal,
						 uint8_t **pub_key_bytes,
						 int *pub_key_len)
{
	char	   *key_algo;
	bool		is_ec = true;	/* default to EC-ElGamal */
	Oid			real_oid = InvalidOid;	/* ReqID:TECC4.0 - shared by both strategies */

	if (is_ec_elgamal)
		*is_ec_elgamal = true;
	if (pub_key_bytes)
		*pub_key_bytes = NULL;
	if (pub_key_len)
		*pub_key_len = 0;


	/* If DEK OID is invalid, use default (EC-ElGamal) */
	if (!OidIsValid(dek_oid))
		return 0;

	/*
	 * Strategy 1: Look up key_algo from hg_dek_args.
	 * dek_oid here is the distributed ID from CipherDataType; translate it
	 * to the real hg_dek.oid (hg_dek_args is keyed by that) before reading.
	 * real_oid is also reused by strategy 2 below.
	 */
	if (he_resolve_dek_oid(dek_oid, &real_oid) && OidIsValid(real_oid))
	{
		key_algo = get_dek_arg_value(real_oid, "key_algo");

		if (key_algo != NULL)
		{
			if (strcmp(key_algo, "he-mul") == 0)
				is_ec = false;
			else if (strcmp(key_algo, "he-add") == 0)
				is_ec = true;
			/* else: unknown key_algo, use default */
			pfree(key_algo);

			if (is_ec_elgamal)
				*is_ec_elgamal = is_ec;
			return 0;
		}
	}
	key_algo = NULL;

	/*
	 * ReqID:TECC4.0 - Strategy 2: Detect from hg_encrypted_columns encryption
	 * type mask. hg_encrypted_columns is keyed by the local hg_dek.oid, so scan
	 * the resolved real_oid (falling back to dek_oid only if resolution failed,
	 * in which case no row matches and the undetermined scheme is reported).
	 */
	{
		bool		found = false;

		he_detect_key_type_from_columns(OidIsValid(real_oid) ? real_oid : dek_oid,
										&is_ec, &found);

		/*
		 * ReqID:TECC4.0 - 两条策略都没定出方案时，下面会退回默认 EC-ElGamal。
		 * 按 hg_tecc.strict_metadata 报告（默认直接报错）。
		 */
		if (!found)
			tecc_report_undetermined_he_scheme(dek_oid);
	}

	if (is_ec_elgamal)
		*is_ec_elgamal = is_ec;

	return 0;
}

/*
 * Look up a public key by DEK OID.
 * Returns parsed key material from the cache (populated on miss).
 *
 * For EC-ElGamal (he-add): returns EC_GROUP *group + EC_POINT *pub_key (Q)
 * For finite field ElGamal (he-mul): returns BIGNUM *p, *g, *pub_key (h)
 *
 * The key type is determined by looking up the DEK's key_algo in
 * hg_dek_args (set during CREATE DEK).
 */
int
he_get_pubkey(Oid dek_oid,
			  bool prefer_ec,
			  bool *is_ec_elgamal,
			  void **pub_key,
			  void **group,
			  BIGNUM **p,
			  BIGNUM **q,
			  BIGNUM **g)
{
	HEPubKeyCache *entry;
	bool		found;

	/* ReqID:TECC4.0 - Lazy 注册 relcache 失效回调（首次进入时注册一次），
	 * 使 DEK/DEK args 变更时失效 HE 公钥缓存。 */
	if (!he_cache_callback_registered)
	{
		CacheRegisterRelcacheCallback(he_pubkey_cache_relcallback, (Datum) 0);
		he_cache_callback_registered = true;
	}

	/* ReqID:TECC4.0 - Lazy 创建多键哈希表缓存。 */
	if (he_key_cache_htab == NULL)
		he_pubkey_cache_init();

	/* 缓存查找（键 = dek_oid） */
	entry = (HEPubKeyCache *) hash_search(he_key_cache_htab, &dek_oid,
										  HASH_FIND, &found);
	if (found)
	{
		/* 命中：直接返回缓存公钥 */
		if (is_ec_elgamal)
			*is_ec_elgamal = (entry->key_type == HE_KEY_EC_ELGAMAL);

		if (entry->key_type == HE_KEY_EC_ELGAMAL)
		{
			if (pub_key) *pub_key = (void *) entry->ec_Q;
			if (group) *group = (void *) entry->ec_group;
			if (p) *p = NULL;
			if (q) *q = NULL;
			if (g) *g = NULL;
		}
		else if (entry->key_type == HE_KEY_ELGAMAL)
		{
			if (pub_key) *pub_key = (void *) entry->ff_h;
			if (group) *group = NULL;
			if (p) *p = entry->ff_p;
			if (q) *q = entry->ff_q;
			if (g) *g = entry->ff_g;
		}
		else
			return -1;
		return 0;
	}

	/* Cache miss: 先完成全部目录读取，再建/填缓存条目。
	 *
	 * ReqID:TECC4.0 - 顺序至关重要：he_fetch_pubkey_from_dek() /
	 * he_load_real_pubkey() 都要读 hg_dek / hg_dek_args，syscache 未命中时
	 * SearchCatCache() 会调用 AcceptInvalidationMessages()，从而在本函数执行
	 * 中途触发 he_pubkey_cache_relcallback() → he_pubkey_cache_invalidate()，
	 * 把整份缓存（含**正在填充的条目**）的 BIGNUM/EC_POINT 释放并 hash_destroy。
	 * 旧实现先把空条目插入再读目录，于是继续写入的是已释放内存、返回给调用方的
	 * 是已释放的 p/q/g/h 指针，同态运算随机报 "homomorphic multiplication
	 * failed"/"ElGamal scalar multiplication failed"（实测该 p 为 NULL）。
	 * 现在改为：先把目录读全，再（必要时重建哈希表）插入并一次性填充条目；
	 * 插入后本函数不再访问目录，条目不可能再被失效打断。 */
	{
		bool		is_ec = true;
		bool		real_is_ec = true;
		int			ret;
		EC_GROUP   *ec_group = NULL;
		EC_POINT   *ec_Q = NULL;
		BIGNUM	   *ff_p = NULL;
		BIGNUM	   *ff_q = NULL;
		BIGNUM	   *ff_g = NULL;
		BIGNUM	   *ff_h = NULL;

		/* 1) 读 DEK 元数据，判定密钥类型（EC-ElGamal / 有限域 ElGamal） */
		ret = he_fetch_pubkey_from_dek(dek_oid, &real_is_ec, NULL, NULL);
		if (ret != 0)
			return -1;

		/* Apply caller preference override */
		is_ec = (real_is_ec != prefer_ec) ? prefer_ec : real_is_ec;

		if (is_ec)
		{
			/* EC-ElGamal: create P-256 group */
			ec_group = tecc_ec_elgamal_create_group();
			if (ec_group == NULL)
				return -1;

			/* ReqID:TECC4.0 - 从 hg_dek_args 加载真实 EC 公钥；缺失时报错，
			 * 不再回退到生成元（生成元等价私钥=1，任何知晓者可解出常量明文）。 */
			if (he_load_real_pubkey(dek_oid, true, ec_group, &ec_Q, NULL) != 0 ||
				ec_Q == NULL)
			{
				EC_GROUP_free(ec_group);
				ereport(ERROR,
						(errcode(ERRCODE_INVALID_PARAMETER_VALUE),
						 errmsg("column encryption key with distributed ID %u lacks EC-ElGamal public key material", dek_oid),
						 errhint("Recreate the column encryption key with homomorphic encryption key material.")));
			}
			elog(DEBUG1, "he_operators: loaded real EC pubkey for DEK dist %u", dek_oid);
		}
		else
		{
			/* Load default 2048-bit parameters (same as used by client-side
			 * tecc_algorithm_scheduler.c:he_eg_init()) */
			ret = tecc_elgamal_get_default_params(&ff_p, &ff_q, &ff_g);
			if (ret != TECC_ELGAMAL_SUCCESS)
				return -1;

			/* ReqID:TECC4.0 - 从 hg_dek_args 加载真实 FF 公钥；缺失时报错，
			 * 不再回退到 h = g（私钥=1）。 */
			if (he_load_real_pubkey(dek_oid, false, NULL, NULL, &ff_h) != 0 ||
				ff_h == NULL)
			{
				BN_free(ff_p);
				BN_free(ff_q);
				BN_free(ff_g);
				ereport(ERROR,
						(errcode(ERRCODE_INVALID_PARAMETER_VALUE),
						 errmsg("column encryption key with distributed ID %u lacks ElGamal public key material", dek_oid),
						 errhint("Recreate the column encryption key with homomorphic encryption key material.")));
			}
			elog(DEBUG1, "he_operators: loaded real FF pubkey for DEK dist %u", dek_oid);
		}

		/* 2) 目录读取已全部完成，以下为纯内存操作：建表（可能已被失效销毁）→
		 *    插入条目 → 一次性填充。 */
		if (he_key_cache_htab == NULL)
			he_pubkey_cache_init();

		entry = (HEPubKeyCache *) hash_search(he_key_cache_htab, &dek_oid,
											  HASH_ENTER, &found);
		if (entry == NULL)
		{
			if (ec_group != NULL)
				EC_GROUP_free(ec_group);
			if (ec_Q != NULL)
				EC_POINT_free(ec_Q);
			BN_free(ff_p);
			BN_free(ff_q);
			BN_free(ff_g);
			BN_free(ff_h);
			return -1;
		}

		if (found)
		{
			/* 本函数读目录期间不会递归填充缓存，理论上不会命中；保守复用已有条目 */
			if (ec_group != NULL)
				EC_GROUP_free(ec_group);
			if (ec_Q != NULL)
				EC_POINT_free(ec_Q);
			BN_free(ff_p);
			BN_free(ff_q);
			BN_free(ff_g);
			BN_free(ff_h);
		}
		else
		{
			entry->key_type = is_ec ? HE_KEY_EC_ELGAMAL : HE_KEY_ELGAMAL;
			entry->ec_group = ec_group;
			entry->ec_Q = ec_Q;
			entry->ff_p = ff_p;
			entry->ff_q = ff_q;
			entry->ff_g = ff_g;
			entry->ff_h = ff_h;
		}

		/* 3) 返回条目内容（字段语义与缓存命中路径一致） */
		if (is_ec_elgamal)
			*is_ec_elgamal = is_ec;
		if (is_ec)
		{
			if (pub_key)
				*pub_key = (void *) entry->ec_Q;
			if (group)
				*group = (void *) entry->ec_group;
			if (p) *p = NULL;
			if (q) *q = NULL;
			if (g) *g = NULL;
		}
		else
		{
			if (pub_key)
				*pub_key = (void *) entry->ff_h;
			if (group)
				*group = NULL;
			if (p) *p = entry->ff_p;
			if (q) *q = entry->ff_q;
			if (g) *g = entry->ff_g;
		}
	}

	return 0;
}

/* ==================== Result Construction ==================== */

/*
 * Build a HE result CipherDataType.
 *
 * Allocates a new CipherDataType with the EG_ADD slot filled from
 * the CRT ciphertext result (EC-ElGamal case).  Other slots (RND,
 * DET, OPE, SEARCH, EG_MUL) are left empty.
 */
static CipherDataType *
build_he_add_result(const TeccECCRTCiphertext *ct,
					const EC_GROUP *group,
					Oid dek_dist_oid, BN_CTX *ctx)
{
	CipherDataType *result;
	uint8_t		serialized[TECC_EC_CRT_MAX_CIPHERTEXT_SIZE];
	int			serial_len;
	int32		eg_add_len;

	/* Serialize the CRT ciphertext */
	serial_len = tecc_ec_crt_serialize_ex(serialized, sizeof(serialized),
										  ct, group, ctx);
	if (serial_len <= 0)
		ereport(ERROR,
				(errcode(ERRCODE_INTERNAL_ERROR),
				 errmsg("failed to serialize EC-ElGamal ciphertext")));

	eg_add_len = (int32) serial_len + CIPHERDATA_HE_DEK_ID_SIZE;

	/* Allocate with only the EG_ADD slot filled */
	result = cipherdata_alloc(0, 0, 0, 0, eg_add_len, 0, dek_dist_oid);

	/* Copy EG_ADD ciphertext data: [dek_id:4][serialized ciphertext] */
	if (eg_add_len > 0)
	{
		memcpy(CIPHERDATA_EG_ADD_PTR(result), &dek_dist_oid,
			   CIPHERDATA_HE_DEK_ID_SIZE);
		memcpy(CIPHERDATA_EG_ADD_PTR(result) + CIPHERDATA_HE_DEK_ID_SIZE,
			   serialized, serial_len);
	}

	return result;
}

/*
 * Build a HE result with EG_MUL slot filled (ElGamal case).
 */
static CipherDataType *
build_he_mul_result(const BIGNUM *res_c1, const BIGNUM *res_c2,
					Oid dek_dist_oid)
{
	CipherDataType *result;
	uint8_t		serialized[TECC_ELGAMAL_CIPHERTEXT_SIZE];
	int			serial_len;
	int32		eg_mul_len;

	/* Serialize the ElGamal ciphertext */
	serial_len = tecc_elgamal_serialize(serialized, sizeof(serialized),
										res_c1, res_c2);
	if (serial_len <= 0)
		ereport(ERROR,
				(errcode(ERRCODE_INTERNAL_ERROR),
				 errmsg("failed to serialize ElGamal ciphertext")));

	eg_mul_len = (int32) serial_len + CIPHERDATA_HE_DEK_ID_SIZE;

	/* Allocate with only the EG_MUL slot filled */
	result = cipherdata_alloc(0, 0, 0, 0, 0, eg_mul_len, dek_dist_oid);

	/* Copy EG_MUL ciphertext data: [dek_id:4][serialized ciphertext] */
	if (eg_mul_len > 0)
	{
		memcpy(CIPHERDATA_EG_MUL_PTR(result), &dek_dist_oid,
			   CIPHERDATA_HE_DEK_ID_SIZE);
		memcpy(CIPHERDATA_EG_MUL_PTR(result) + CIPHERDATA_HE_DEK_ID_SIZE,
			   serialized, serial_len);
	}

	return result;
}

/*
 * Build a result with both EG_ADD and EG_MUL slots.
 */
static CipherDataType *
build_he_both_result(const TeccECCRTCiphertext *ct_add,
					 const EC_GROUP *group,
					 const BIGNUM *res_c1, const BIGNUM *res_c2,
					 Oid dek_dist_oid)
{
	CipherDataType *result;
	uint8_t		add_serial[TECC_EC_CRT_MAX_CIPHERTEXT_SIZE];
	uint8_t		mul_serial[TECC_ELGAMAL_CIPHERTEXT_SIZE];
	int			add_len;
	int			mul_len;

	add_len = tecc_ec_crt_serialize(add_serial, sizeof(add_serial),
									ct_add, group);
	mul_len = tecc_elgamal_serialize(mul_serial, sizeof(mul_serial),
									 res_c1, res_c2);

	if (add_len <= 0 || mul_len <= 0)
		ereport(ERROR,
				(errcode(ERRCODE_INTERNAL_ERROR),
				 errmsg("failed to serialize HE ciphertext")));

	result = cipherdata_alloc(0, 0, 0, 0,
							  (int32) add_len + CIPHERDATA_HE_DEK_ID_SIZE,
							  (int32) mul_len + CIPHERDATA_HE_DEK_ID_SIZE,
							  dek_dist_oid);

	/* Copy both segments: [dek_id:4][serialized ciphertext] */
	if (add_len > 0)
	{
		memcpy(CIPHERDATA_EG_ADD_PTR(result), &dek_dist_oid,
			   CIPHERDATA_HE_DEK_ID_SIZE);
		memcpy(CIPHERDATA_EG_ADD_PTR(result) + CIPHERDATA_HE_DEK_ID_SIZE,
			   add_serial, add_len);
	}
	if (mul_len > 0)
	{
		memcpy(CIPHERDATA_EG_MUL_PTR(result), &dek_dist_oid,
			   CIPHERDATA_HE_DEK_ID_SIZE);
		memcpy(CIPHERDATA_EG_MUL_PTR(result) + CIPHERDATA_HE_DEK_ID_SIZE,
			   mul_serial, mul_len);
	}

	return result;
}

/* ==================== HE Operator Implementation ==================== */

/*
 * Generic HE addition: a + b (both operands must have EG_ADD slot).
 *
 * Extracts the CRT ciphertexts from both operands, adds them
 * homomorphically using EC-ElGamal addition, and returns the result.
 */
static Datum
he_add_generic(PG_FUNCTION_ARGS, Oid type_oid)
{
	CipherDataType *a = (CipherDataType *) PG_DETOAST_DATUM(PG_GETARG_DATUM(0));
	CipherDataType *b = (CipherDataType *) PG_DETOAST_DATUM(PG_GETARG_DATUM(1));
	Oid			dek_oid;
	bool		is_ec;
	void	   *pub_key;
	void	   *group;
	BIGNUM	   *p;
	BIGNUM	   *g;
	BIGNUM	   *q;
	TeccECCRTCiphertext ct_a;
	TeccECCRTCiphertext ct_b;
	TeccECCRTCiphertext ct_res;
	CipherDataType *result;
	BN_CTX	   *bn_ctx;

	/* Validate both operands have EG_ADD data */
	if (CIPHERDATA_DATUM_EG_ADD_LEN(a) <= 0 ||
		CIPHERDATA_DATUM_EG_ADD_LEN(b) <= 0)
		ereport(ERROR,
				(errcode(ERRCODE_TECC_ALGORITHM_INCOMPATIBLE),
				 errmsg("cannot perform homomorphic addition: operand lacks EG_ADD ciphertext"),
				 errhint("Ensure the column has support_algo='he-add' set.")));

	/* Both operands must use the same DEK (per-segment DEK identity) */
	dek_oid = CIPHERDATA_DATUM_EG_ADD_DEK_ID(a);
	if (dek_oid != CIPHERDATA_DATUM_EG_ADD_DEK_ID(b))
		ereport(ERROR,
				(errcode(ERRCODE_TECC_DEK_MISMATCH),
				 errmsg("cannot perform homomorphic addition: DEK mismatch")));

	/* Get public key */
	if (he_get_pubkey(dek_oid, true, &is_ec, &pub_key, &group, &p, &q, &g) != 0)
		ereport(ERROR,
				(errcode(ERRCODE_INTERNAL_ERROR),
				 errmsg("failed to retrieve HE public key for DEK %u", dek_oid)));

	if (!is_ec)
		ereport(ERROR,
				(errcode(ERRCODE_TECC_ALGORITHM_INCOMPATIBLE),
				 errmsg("EC-ElGamal public key required for homomorphic addition")));

	bn_ctx = BN_CTX_new();
	if (bn_ctx == NULL)
		ereport(ERROR,
				(errcode(ERRCODE_OUT_OF_MEMORY),
				 errmsg("out of memory")));

	/* Deserialize ciphertexts */
	memset(&ct_a, 0, sizeof(ct_a));
	memset(&ct_b, 0, sizeof(ct_b));
	memset(&ct_res, 0, sizeof(ct_res));

	if (tecc_ec_crt_deserialize_ex(&ct_a,
								CIPHERDATA_DATUM_EG_ADD_CT_PTR(a),
								CIPHERDATA_DATUM_EG_ADD_CT_LEN(a),
								(EC_GROUP *)group, bn_ctx) != 0 ||
		tecc_ec_crt_deserialize_ex(&ct_b,
								CIPHERDATA_DATUM_EG_ADD_CT_PTR(b),
								CIPHERDATA_DATUM_EG_ADD_CT_LEN(b),
								(EC_GROUP *)group, bn_ctx) != 0)
	{
		tecc_ec_crt_ciphertext_free(&ct_a, (EC_GROUP *)group);
		tecc_ec_crt_ciphertext_free(&ct_b, (EC_GROUP *)group);
		BN_CTX_free(bn_ctx);
		ereport(ERROR,
				(errcode(ERRCODE_INVALID_BINARY_REPRESENTATION),
				 errmsg("invalid EC-ElGamal ciphertext")));
	}

	/* Initialize result ciphertext */
	if (tecc_ec_crt_ciphertext_init(&ct_res, (EC_GROUP *)group,
									ct_a.num_ciphertexts) != 0)
	{
		tecc_ec_crt_ciphertext_free(&ct_a, (EC_GROUP *)group);
		tecc_ec_crt_ciphertext_free(&ct_b, (EC_GROUP *)group);
		BN_CTX_free(bn_ctx);
		ereport(ERROR,
				(errcode(ERRCODE_OUT_OF_MEMORY),
				 errmsg("out of memory")));
	}

	/* Perform homomorphic addition */
	if (tecc_ec_crt_add((EC_GROUP *)group, &ct_res, &ct_a, &ct_b,
						bn_ctx) != 0)
	{
		tecc_ec_crt_ciphertext_free(&ct_a, (EC_GROUP *)group);
		tecc_ec_crt_ciphertext_free(&ct_b, (EC_GROUP *)group);
		tecc_ec_crt_ciphertext_free(&ct_res, (EC_GROUP *)group);
		BN_CTX_free(bn_ctx);
		ereport(ERROR,
				(errcode(ERRCODE_INTERNAL_ERROR),
				 errmsg("homomorphic addition failed")));
	}

	/* Build result */
	result = build_he_add_result(&ct_res, (EC_GROUP *)group, dek_oid, bn_ctx);

	/* Cleanup */
	tecc_ec_crt_ciphertext_free(&ct_a, (EC_GROUP *)group);
	tecc_ec_crt_ciphertext_free(&ct_b, (EC_GROUP *)group);
	tecc_ec_crt_ciphertext_free(&ct_res, (EC_GROUP *)group);
	BN_CTX_free(bn_ctx);

	PG_RETURN_POINTER(result);
}

/*
 * Generic HE subtraction: a - b
 */
static Datum
he_sub_generic(PG_FUNCTION_ARGS, Oid type_oid)
{
	CipherDataType *a = (CipherDataType *) PG_DETOAST_DATUM(PG_GETARG_DATUM(0));
	CipherDataType *b = (CipherDataType *) PG_DETOAST_DATUM(PG_GETARG_DATUM(1));
	Oid			dek_oid;
	bool		is_ec;
	void	   *pub_key;
	void	   *group;
	BIGNUM	   *p;
	BIGNUM	   *g;
	BIGNUM	   *q;
	TeccECCRTCiphertext ct_a;
	TeccECCRTCiphertext ct_b;
	TeccECCRTCiphertext ct_res;
	CipherDataType *result;
	BN_CTX	   *bn_ctx;

	if (CIPHERDATA_DATUM_EG_ADD_LEN(a) <= 0 ||
		CIPHERDATA_DATUM_EG_ADD_LEN(b) <= 0)
		ereport(ERROR,
				(errcode(ERRCODE_TECC_ALGORITHM_INCOMPATIBLE),
				 errmsg("cannot perform homomorphic subtraction: operand lacks EG_ADD ciphertext")));

	dek_oid = CIPHERDATA_DATUM_EG_ADD_DEK_ID(a);
	if (dek_oid != CIPHERDATA_DATUM_EG_ADD_DEK_ID(b))
		ereport(ERROR,
				(errcode(ERRCODE_TECC_DEK_MISMATCH),
				 errmsg("cannot perform homomorphic subtraction: DEK mismatch")));

	if (he_get_pubkey(dek_oid, true, &is_ec, &pub_key, &group, &p, &q, &g) != 0)
		ereport(ERROR,
				(errcode(ERRCODE_INTERNAL_ERROR),
				 errmsg("failed to retrieve HE public key")));

	if (!is_ec)
		ereport(ERROR,
				(errcode(ERRCODE_TECC_ALGORITHM_INCOMPATIBLE),
				 errmsg("EC-ElGamal public key required for homomorphic subtraction")));

	bn_ctx = BN_CTX_new();
	memset(&ct_a, 0, sizeof(ct_a));
	memset(&ct_b, 0, sizeof(ct_b));
	memset(&ct_res, 0, sizeof(ct_res));

	if (tecc_ec_crt_deserialize_ex(&ct_a,
								CIPHERDATA_DATUM_EG_ADD_CT_PTR(a),
								CIPHERDATA_DATUM_EG_ADD_CT_LEN(a),
								(EC_GROUP *)group, bn_ctx) != 0 ||
		tecc_ec_crt_deserialize_ex(&ct_b,
								CIPHERDATA_DATUM_EG_ADD_CT_PTR(b),
								CIPHERDATA_DATUM_EG_ADD_CT_LEN(b),
								(EC_GROUP *)group, bn_ctx) != 0)
	{
		tecc_ec_crt_ciphertext_free(&ct_a, (EC_GROUP *)group);
		tecc_ec_crt_ciphertext_free(&ct_b, (EC_GROUP *)group);
		BN_CTX_free(bn_ctx);
		ereport(ERROR,
				(errcode(ERRCODE_INVALID_BINARY_REPRESENTATION),
				 errmsg("invalid EC-ElGamal ciphertext")));
	}

	if (tecc_ec_crt_ciphertext_init(&ct_res, (EC_GROUP *)group,
									ct_a.num_ciphertexts) != 0)
	{
		tecc_ec_crt_ciphertext_free(&ct_a, (EC_GROUP *)group);
		tecc_ec_crt_ciphertext_free(&ct_b, (EC_GROUP *)group);
		BN_CTX_free(bn_ctx);
		ereport(ERROR,
				(errcode(ERRCODE_OUT_OF_MEMORY),
				 errmsg("out of memory")));
	}

	if (tecc_ec_crt_sub((EC_GROUP *)group, &ct_res, &ct_a, &ct_b,
						bn_ctx) != 0)
	{
		tecc_ec_crt_ciphertext_free(&ct_a, (EC_GROUP *)group);
		tecc_ec_crt_ciphertext_free(&ct_b, (EC_GROUP *)group);
		tecc_ec_crt_ciphertext_free(&ct_res, (EC_GROUP *)group);
		BN_CTX_free(bn_ctx);
		ereport(ERROR,
				(errcode(ERRCODE_INTERNAL_ERROR),
				 errmsg("homomorphic subtraction failed")));
	}

	result = build_he_add_result(&ct_res, (EC_GROUP *)group, dek_oid, bn_ctx);

	tecc_ec_crt_ciphertext_free(&ct_a, (EC_GROUP *)group);
	tecc_ec_crt_ciphertext_free(&ct_b, (EC_GROUP *)group);
	tecc_ec_crt_ciphertext_free(&ct_res, (EC_GROUP *)group);
	BN_CTX_free(bn_ctx);

	PG_RETURN_POINTER(result);
}

/*
 * Generic HE multiplication: a * b (both must have EG_MUL slot).
 */
static Datum
he_mul_generic(PG_FUNCTION_ARGS, Oid type_oid)
{
	CipherDataType *a = (CipherDataType *) PG_DETOAST_DATUM(PG_GETARG_DATUM(0));
	CipherDataType *b = (CipherDataType *) PG_DETOAST_DATUM(PG_GETARG_DATUM(1));
	Oid			dek_oid;
	bool		is_ec;
	void	   *pub_key;
	void	   *group;
	BIGNUM	   *p;
	BIGNUM	   *g;
	BIGNUM	   *q;
	BIGNUM	   *a_c1;
	BIGNUM	   *a_c2;
	BIGNUM	   *b_c1;
	BIGNUM	   *b_c2;
	BIGNUM	   *res_c1;
	BIGNUM	   *res_c2;
	CipherDataType *result;
	BN_CTX	   *bn_ctx;

	if (CIPHERDATA_DATUM_EG_MUL_LEN(a) <= 0 ||
		CIPHERDATA_DATUM_EG_MUL_LEN(b) <= 0)
		ereport(ERROR,
				(errcode(ERRCODE_TECC_ALGORITHM_INCOMPATIBLE),
				 errmsg("cannot perform homomorphic multiplication: operand lacks EG_MUL ciphertext"),
				 errhint("Ensure the column has support_algo='he-mul' set.")));

	dek_oid = CIPHERDATA_DATUM_EG_MUL_DEK_ID(a);
	if (dek_oid != CIPHERDATA_DATUM_EG_MUL_DEK_ID(b))
		ereport(ERROR,
				(errcode(ERRCODE_TECC_DEK_MISMATCH),
				 errmsg("cannot perform homomorphic multiplication: DEK mismatch")));

	if (he_get_pubkey(dek_oid, false, &is_ec, &pub_key, &group, &p, &q, &g) != 0)
		ereport(ERROR,
				(errcode(ERRCODE_INTERNAL_ERROR),
				 errmsg("failed to retrieve HE public key")));

	if (is_ec)
		ereport(ERROR,
				(errcode(ERRCODE_TECC_ALGORITHM_INCOMPATIBLE),
				 errmsg("finite field ElGamal public key required for homomorphic multiplication")));

	bn_ctx = BN_CTX_new();
	a_c1 = BN_new(); a_c2 = BN_new();
	b_c1 = BN_new(); b_c2 = BN_new();
	res_c1 = BN_new(); res_c2 = BN_new();

	if (a_c1 == NULL || a_c2 == NULL || b_c1 == NULL || b_c2 == NULL ||
		res_c1 == NULL || res_c2 == NULL || bn_ctx == NULL)
	{
		BN_free(a_c1); BN_free(a_c2); BN_free(b_c1); BN_free(b_c2);
		BN_free(res_c1); BN_free(res_c2);
		BN_CTX_free(bn_ctx);
		ereport(ERROR,
				(errcode(ERRCODE_OUT_OF_MEMORY),
				 errmsg("out of memory")));
	}

	/* Deserialize ciphertexts */
	if (tecc_elgamal_deserialize(a_c1, a_c2,
								 CIPHERDATA_DATUM_EG_MUL_CT_PTR(a),
								 CIPHERDATA_DATUM_EG_MUL_CT_LEN(a)) != 0 ||
		tecc_elgamal_deserialize(b_c1, b_c2,
								 CIPHERDATA_DATUM_EG_MUL_CT_PTR(b),
								 CIPHERDATA_DATUM_EG_MUL_CT_LEN(b)) != 0)
	{
		BN_free(a_c1); BN_free(a_c2); BN_free(b_c1); BN_free(b_c2);
		BN_free(res_c1); BN_free(res_c2);
		BN_CTX_free(bn_ctx);
		ereport(ERROR,
				(errcode(ERRCODE_INVALID_BINARY_REPRESENTATION),
				 errmsg("invalid ElGamal ciphertext")));
	}

	/* Homomorphic multiplication */
	if (tecc_elgamal_mul(p, res_c1, res_c2,
						 a_c1, a_c2, b_c1, b_c2, bn_ctx) != 0)
	{
		BN_free(a_c1); BN_free(a_c2); BN_free(b_c1); BN_free(b_c2);
		BN_free(res_c1); BN_free(res_c2);
		BN_CTX_free(bn_ctx);
		ereport(ERROR,
				(errcode(ERRCODE_INTERNAL_ERROR),
				 errmsg("homomorphic multiplication failed")));
	}

	result = build_he_mul_result(res_c1, res_c2, dek_oid);

	BN_free(a_c1); BN_free(a_c2); BN_free(b_c1); BN_free(b_c2);
	BN_free(res_c1); BN_free(res_c2);
	BN_CTX_free(bn_ctx);

	PG_RETURN_POINTER(result);
}

/*
 * ReqID:TECC4.0 - Homomorphic power (exponentiation): a^n over finite-field
 * ElGamal ciphertext, E(m)^n = (c1^n mod p, c2^n mod p), computed by
 * square-and-multiply (~2*log2(n) ciphertext multiplications).
 *
 * Only supported on columns with EG_MUL ciphertext (support_algo='he-mul');
 * EC-ElGamal (he-add) columns have no multiplicative homomorphism and raise
 * an error, mirroring he_mul_generic's EG_MUL slot check.
 */
static Datum
he_mul_pow_core(PG_FUNCTION_ARGS, Oid type_oid, Datum enc_datum, int64 n)
{
	CipherDataType *a = (CipherDataType *) PG_DETOAST_DATUM(enc_datum);
	Oid			dek_oid;
	bool		is_ec;
	void	   *pub_key;
	void	   *group;
	BIGNUM	   *p;
	BIGNUM	   *g;
	BIGNUM	   *q;
	BIGNUM	   *n_bn;
	BIGNUM	   *a_c1;
	BIGNUM	   *a_c2;
	BIGNUM	   *res_c1;
	BIGNUM	   *res_c2;
	CipherDataType *result;
	BN_CTX	   *bn_ctx;

	if (CIPHERDATA_DATUM_EG_MUL_LEN(a) <= 0)
		ereport(ERROR,
				(errcode(ERRCODE_TECC_ALGORITHM_INCOMPATIBLE),
				 errmsg("cannot perform homomorphic power: operand lacks EG_MUL ciphertext"),
				 errhint("Ensure the column has support_algo='he-mul' set.")));

	if (n <= 0)
		ereport(ERROR,
				(errcode(ERRCODE_INVALID_PARAMETER_VALUE),
				 errmsg("homomorphic power exponent must be positive")));

	/* ReqID:TECC4.0 - 指数上限沿用历史值（超出即报错，用例已固化该文案）。
	 * 改为平方-乘后单行成本已降为 O(log n)，该上限不再是防 DoS 必需，
	 * 是否放宽属独立变更 */
	if (n > TECC_HE_POW_MAX_EXPONENT)
		ereport(ERROR,
				(errcode(ERRCODE_INVALID_PARAMETER_VALUE),
				 errmsg("homomorphic power exponent %lld exceeds maximum allowed value %d",
						(long long) n, TECC_HE_POW_MAX_EXPONENT)));

	dek_oid = CIPHERDATA_DATUM_EG_MUL_DEK_ID(a);

	if (he_get_pubkey(dek_oid, false, &is_ec, &pub_key, &group, &p, &q, &g) != 0)
		ereport(ERROR,
				(errcode(ERRCODE_INTERNAL_ERROR),
				 errmsg("failed to retrieve HE public key")));

	if (is_ec)
		ereport(ERROR,
				(errcode(ERRCODE_TECC_ALGORITHM_INCOMPATIBLE),
				 errmsg("finite field ElGamal public key required for homomorphic power")));

	bn_ctx = BN_CTX_new();
	a_c1 = BN_new(); a_c2 = BN_new();
	res_c1 = BN_new(); res_c2 = BN_new();

	if (a_c1 == NULL || a_c2 == NULL || res_c1 == NULL || res_c2 == NULL ||
		bn_ctx == NULL)
	{
		BN_free(a_c1); BN_free(a_c2); BN_free(res_c1); BN_free(res_c2);
		BN_CTX_free(bn_ctx);
		ereport(ERROR,
				(errcode(ERRCODE_OUT_OF_MEMORY),
				 errmsg("out of memory")));
	}

	/* Deserialize ciphertext */
	if (tecc_elgamal_deserialize(a_c1, a_c2,
								 CIPHERDATA_DATUM_EG_MUL_CT_PTR(a),
								 CIPHERDATA_DATUM_EG_MUL_CT_LEN(a)) != 0)
	{
		BN_free(a_c1); BN_free(a_c2); BN_free(res_c1); BN_free(res_c2);
		BN_CTX_free(bn_ctx);
		ereport(ERROR,
				(errcode(ERRCODE_INVALID_BINARY_REPRESENTATION),
				 errmsg("invalid ElGamal ciphertext")));
	}

	/*
	 * ReqID:TECC4.0 - 同态幂改用平方-乘（二进制快速幂）：E(m)^n =
	 * (c1^n mod p, c2^n mod p)。原来是 n-1 次密文相乘（O(n)），现为
	 * 约 2*log2(n) 次；两者结果逐位相同，密文格式与客户端解密行为不变。
	 * 指数已由上面的上限校验限制在 10000 以内，转 BN_ULONG 不会截断。
	 */
	n_bn = BN_new();
	if (n_bn == NULL || BN_set_word(n_bn, (BN_ULONG) n) == 0)
	{
		BN_free(n_bn);
		BN_free(a_c1); BN_free(a_c2); BN_free(res_c1); BN_free(res_c2);
		BN_CTX_free(bn_ctx);
		ereport(ERROR,
				(errcode(ERRCODE_OUT_OF_MEMORY),
				 errmsg("out of memory")));
	}

	if (tecc_elgamal_pow(p, res_c1, res_c2, a_c1, a_c2, n_bn, bn_ctx) != 0)
	{
		BN_free(n_bn);
		BN_free(a_c1); BN_free(a_c2); BN_free(res_c1); BN_free(res_c2);
		BN_CTX_free(bn_ctx);
		ereport(ERROR,
				(errcode(ERRCODE_INTERNAL_ERROR),
				 errmsg("homomorphic power failed")));
	}
	BN_free(n_bn);

	result = build_he_mul_result(res_c1, res_c2, dek_oid);

	BN_free(a_c1); BN_free(a_c2); BN_free(res_c1); BN_free(res_c2);
	BN_CTX_free(bn_ctx);

	PG_RETURN_POINTER(result);
}

