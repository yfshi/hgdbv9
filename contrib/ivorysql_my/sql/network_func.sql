-- IPv4 Tests: INET_ATON and INET_NTOA

-- Basic valid IPv4
SELECT INET_ATON('127.0.0.1');
SELECT INET_NTOA(2130706433);

SELECT INET_ATON('192.168.1.1');
SELECT INET_NTOA(3232235777);

select INET_ATON(true),INET_ATON(false),INET_NTOA(true),INET_NTOA(false);

-- Compressed format
SELECT INET_ATON('10.1');
SELECT INET_ATON('10.1.2');
SELECT INET_ATON('10');

-- Boundary values
SELECT INET_ATON('255.255.255.255');
SELECT INET_NTOA(4294967295);
SELECT INET_ATON('0.0.0.0');
SELECT INET_NTOA(0);

-- Invalid format and edge cases
SELECT INET_ATON('256.1.1.1');
SELECT INET_ATON('999.999.999.999');
SELECT INET_ATON('abc');
SELECT INET_ATON('');
SELECT INET_ATON(NULL);

-- IPv6 Tests: INET6_ATON and INET6_NTOA

-- Reversibility tests
SELECT INET6_NTOA(INET6_ATON('::1'));
SELECT INET6_NTOA(INET6_ATON('2001:db8::dead'));

-- Invalid IPv6
SELECT INET6_ATON(':::1');
SELECT INET6_ATON('GGGG::1');
SELECT INET6_ATON('2001:db8');
SELECT INET6_ATON(NULL);
SELECT INET6_NTOA(NULL);
