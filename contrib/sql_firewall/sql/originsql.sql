CREATE PROCEDURE raise_department_budget(p_code text, p_amount numeric)
LANGUAGE plpgsql AS $$
BEGIN
  UPDATE department SET budget = budget + p_amount WHERE code = p_code;
END $$;

CREATE FUNCTION employee_audit_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO audit_log(happened_on, actor, payload)
  VALUES (CURRENT_DATE, current_user,
          jsonb_build_object('op', TG_OP, 'employee_id', NEW.employee_id));
  RETURN NEW;
END $$;

