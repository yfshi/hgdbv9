CREATE TABLE department (
  department_id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  code text NOT NULL UNIQUE,
  name text NOT NULL,
  budget numeric(14,2) NOT NULL DEFAULT 0 CHECK (budget >= 0),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE employee (
  employee_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_id integer REFERENCES department(department_id),
  manager_id bigint REFERENCES employee(employee_id) DEFERRABLE INITIALLY DEFERRED,
  email text NOT NULL UNIQUE,
  full_name text NOT NULL,
  salary numeric(12,2) CHECK (salary >= 0),
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active','leave','closed')),
  skills text[] NOT NULL DEFAULT '{}',
  profile jsonb NOT NULL DEFAULT '{}',
  hired_on date NOT NULL DEFAULT CURRENT_DATE,
  name_key text GENERATED ALWAYS AS (lower(full_name)) STORED
);

CREATE TABLE audit_log (
  log_id bigint GENERATED ALWAYS AS IDENTITY,
  happened_on date NOT NULL,
  actor text,
  payload jsonb,
  PRIMARY KEY (log_id, happened_on)
) PARTITION BY RANGE (happened_on);
