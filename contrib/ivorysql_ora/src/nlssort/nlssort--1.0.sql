    IF $1 > 1 THEN
        return nlssort($1::text);
    END IF;
    
    return nlssort(substr($1::text, 2), $2::unknown);
END;
$$
LANGUAGE plpgsql
STRICT
PARALLEL SAFE
IMMUTABLE;

