CREATE FUNCTION sys.nlssort(double precision)
RETURNS RAW AS 
$$
BEGIN
    IF $1 > 1 THEN
        return nlssort($1::text);
    END IF;
    
    return nlssort(substr($1::text, 2));
END;
$$
LANGUAGE plpgsql
STRICT
PARALLEL SAFE
IMMUTABLE;

CREATE FUNCTION sys.nlssort(double precision, text)
RETURNS RAW AS 
$$
