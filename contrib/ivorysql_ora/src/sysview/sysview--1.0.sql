/* PROSRC LINES COUNT */
--ReqID:SRS-SQL-PACKAGE
--use dynamic sql to support package
CREATE OR REPLACE FUNCTION SYS._ORA_SRC_COUNT(objectid OID,table_name TEXT,
src_name text)
RETURNS INTEGER AS $$
DECLARE
	RET INTEGER;
	stmt_query text;
BEGIN
   /* Begin - BUG#Z370 */
   IF (table_name = 'PG_PROC') THEN
      stmt_query := 'SELECT COUNT(1) from (SELECT UNNEST(STRING_TO_ARRAY(pg_get_functiondef(' || objectid || ')'|| ',CHR(10)))) AS SQ';
   ELSE
   /* End - BUG#Z370 */
     stmt_query := 'SELECT COUNT(1) FROM (SELECT UNNEST(STRING_TO_ARRAY(' || src_name || ',CHR(10)))' ||
       ' FROM ' || table_name || ' WHERE oid = ' || objectid || ') AS SQ';
   /* Begin - BUG#Z370 */
   END IF;
   /* End - BUG#Z370 */

   EXECUTE stmt_query INTO RET;
   RETURN RET;
END;
$$ LANGUAGE PLPGSQL IMMUTABLE;

